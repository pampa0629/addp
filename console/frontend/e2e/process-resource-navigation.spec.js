test('Console switches service scope, preserves module and role, and restores all instances after reload', async ({ page }) => {
  const state = await backend(page, { scopes: true })
  await page.goto('/monitor/service-resources?module_name=monitor&role=worker')
  const monitor = page.frameLocator('iframe[data-testid="module-iframe"]')
  await expect(monitor.getByTestId('process-list')).toContainText('mac-process-1')
  const documentID = await monitor.locator('body').evaluate(() => performance.timeOrigin)
  await monitor.getByRole('button', { name: '全部实例', exact: true }).click()
  await expect(page).toHaveURL(url => url.searchParams.get('status') === 'all' && url.searchParams.get('process_metrics_declared') === 'all' && url.searchParams.get('module_name') === 'monitor' && url.searchParams.get('role') === 'worker')
  await expect(monitor.getByTestId('process-list')).toContainText('history-0')
  expect(await monitor.locator('body').evaluate(() => performance.timeOrigin)).toBe(documentID)
  await page.reload()
  await expect(monitor.getByTestId('process-list')).toContainText('history-0')
  expect(state.listCalls.at(-1)).toMatchObject({ module_name: 'monitor', role: 'worker', page: '1' })
  expect(state.listCalls.at(-1)).not.toHaveProperty('process_metrics_declared')
  await monitor.getByRole('button', { name: '在线且已启用采集', exact: true }).click()
  await expect(page).toHaveURL(url => url.searchParams.get('module_name') === 'monitor' && !url.searchParams.has('status') && !url.searchParams.has('process_metrics_declared'))
  await expect(monitor.getByTestId('process-list')).toContainText('mac-process-1')
})
