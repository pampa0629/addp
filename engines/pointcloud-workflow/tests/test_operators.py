@pytest.mark.parametrize(
    ("operator_name", "suffix", "source_format"),
    [
        ("las_to_copc", ".las", "las"),
        ("laz_to_copc", ".laz", "laz"),
        ("e57_to_copc", ".e57", "e57"),
        ("pcd_to_copc", ".pcd", "pcd"),
        ("xyz_to_copc", ".xyz", "xyz"),
    ],
)
def test_conversion_uses_v1_plan_and_publishes_to_mounted_target(tmp_path, operator_name, suffix, source_format):
    source = tmp_path / f"source{suffix}"
    source.write_bytes(las_header())
    target = tmp_path / "output" / "source.copc.laz"
    pdal = tmp_path / "pdal"
    pdal.write_text("#!/bin/sh\n", encoding="utf-8")
    pdal.chmod(0o755)
    captured = {}

    def fake_runner(command, timeout_seconds):
        captured["command"] = command
        write_native_fixture(command)
        return CommandResult(returncode=0, stdout="translated")

    facts = invoke_operator(
        operator_name,
        {
            "access_plan": mounted_plan(source, target, source_format),
            "options": {"scale_x": 0.01, "threads": 2},
        },
        runner=fake_runner,
        env={"POINTCLOUD_PDAL_BIN": str(pdal)},
    )

    assert target.read_bytes().startswith(b"LASF")
    assert facts["copc_uri"] == str(target)
    assert facts["source_format"] == source_format
    assert facts["quantization"]["scale"][0] == 0.01
    assert facts["quantization"]["offset"] == [1, 2, 3]
    assert facts["quantization"]["point_count"] == 3
    assert facts["quantization"]["selection"]["scale_x"] == "explicit"
    if source_format in {"las", "laz"}:
        assert "--writers.copc.scale_y=0.002" in captured["command"]
        assert facts["quantization"]["selection"]["scale_y"] == "source"
    else:
        assert all("=auto" not in value for value in captured["command"])
        assert facts["quantization"]["selection"]["scale_y"] == "auto"
    assert "--writers.copc.threads=2" in captured["command"]
    if source_format == "xyz":
        assert "readers.text" in captured["command"]


def test_progress_callback_is_separate_from_access_plan(tmp_path, monkeypatch):
    source = tmp_path / "source.las"
    source.write_bytes(las_header())
    target = tmp_path / "source.copc.laz"
    pdal = tmp_path / "pdal"
    pdal.write_text("#!/bin/sh\n", encoding="utf-8")
    pdal.chmod(0o755)
    posted = []

    class FakeTokenSource:
        def __init__(self, system_url, client_id, client_secret):
            assert system_url == "http://system:8180"
            assert client_id == "addp-pointcloud"
            assert client_secret == "pointcloud-secret"

        def token(self, tenant_id):
            assert tenant_id == 7
            return "addp_at_pointcloud"

    class FakeHTTPResponse:
        def __enter__(self):
            return self

        def __exit__(self, exc_type, exc, tb):
            return False

        def read(self):
            return b""

    def fake_urlopen(req, timeout):
        posted.append({
            "payload": json.loads(req.data.decode("utf-8")),
            "headers": dict(req.header_items()),
            "url": req.full_url,
        })
        return FakeHTTPResponse()

    def fake_runner(command, timeout_seconds):
        write_native_fixture(command)
        return CommandResult(returncode=0, stdout="translated")

    monkeypatch.setattr(operators.urlrequest, "urlopen", fake_urlopen)
    monkeypatch.setattr(operators, "SyncOAuthServiceTokenSource", FakeTokenSource)
    monkeypatch.setenv("SYSTEM_URL", "http://system:8180")
    monkeypatch.setenv("POINTCLOUD_WORKFLOW_SERVICE_CLIENT_SECRET", "pointcloud-secret")
    invoke_operator(
        "las_to_copc",
        {
            "access_plan": mounted_plan(source, target, "las"),
            "progress_callback": {
                "endpoint": "http://manager/api/v1/manager/executions/exec-1/events",
                "tenant_id": 7,
                "execution_id": "exec-1",
                "attempt": 2,
                "lease_token": "lease-token",
            },
        },
        runner=fake_runner,
        env={"POINTCLOUD_PDAL_BIN": str(pdal)},
    )
    assert [(item["payload"]["phase"], item["payload"]["event"]) for item in posted] == [
        ("prepare", "started"), ("convert", "started"), ("publish", "started"), ("publish", "completed"),
    ]
    assert {item["url"] for item in posted} == {
        "http://manager/api/v1/manager/executions/exec-1/events"
    }
    assert all(item["headers"].get("Authorization") == "Bearer addp_at_pointcloud" for item in posted)
    assert all("X-internal-api-key" not in item["headers"] for item in posted)
    assert all("X-tenant-id" not in item["headers"] for item in posted)
    assert all(item["payload"]["attempt"] == 2 for item in posted)
    assert all(item["payload"]["lease_token"] == "lease-token" for item in posted)


def test_container_runtime_rewrites_localhost_object_store_endpoints_before_stage_and_publish(tmp_path, monkeypatch):
    source = tmp_path / "source.xyz"
    source.write_text("0 0 0\n", encoding="utf-8")
    target = tmp_path / "source.copc.laz"
    pdal = tmp_path / "pdal"
    pdal.write_text("#!/bin/sh\n", encoding="utf-8")
    pdal.chmod(0o755)
    plan = mounted_plan(source, target, "xyz")
    plan["source"]["access"] = {
        "method": "object_store",
        "endpoint": "127.0.0.1:9002",
        "access_key": "source-ak",
        "secret_key": "source-sk",
        "bucket": "addp",
        "object": "pointcloud/source.xyz",
        "use_ssl": False,
    }
    plan["target"]["access"] = {
        "method": "object_store",
        "endpoint": "127.0.0.1:19000",
        "access_key": "manager-ak",
        "secret_key": "manager-sk",
        "bucket": "manager",
        "object": "tenant_1/source.copc.laz",
        "use_ssl": False,
    }
    staged = {}
    published = {}

    def fake_stage(access_plan, work_dir):
        staged["endpoint"] = access_plan["source"]["access"]["endpoint"]
        staged_source = work_dir / "source.xyz"
        staged_source.write_text("0 0 0\n", encoding="utf-8")
        return staged_source

    def fake_runner(command, timeout_seconds):
        write_native_fixture(command)
        return CommandResult(returncode=0)

    def fake_publish(path, access_plan):
        published["endpoint"] = access_plan["target"]["access"]["endpoint"]
        return {
            "object_uri": "s3://manager/tenant_1/source.copc.laz",
            "object_name": "tenant_1/source.copc.laz",
            "uploaded_bytes": path.stat().st_size,
        }

    monkeypatch.setattr(operators, "stage_source_file", fake_stage)
    monkeypatch.setattr(operators, "publish_target_file", fake_publish)
    invoke_operator(
        "xyz_to_copc",
        {"access_plan": plan},
        runner=fake_runner,
        env={
            "POINTCLOUD_PDAL_BIN": str(pdal),
            "POINTCLOUD_OBJECT_STORE_LOOPBACK_HOST": "host.docker.internal",
        },
    )

    assert staged["endpoint"] == "host.docker.internal:9002"
    assert published["endpoint"] == "host.docker.internal:19000"
    assert plan["source"]["access"]["endpoint"] == "127.0.0.1:9002"
    assert plan["target"]["access"]["endpoint"] == "127.0.0.1:19000"


