def test_precision_selection_preserves_exact_source_doubles_and_partial_overrides(tmp_path):
    source = tmp_path / "source.las"
    scale = [1.23456789012345e-7, 2e-6, 3e-5]
    offset = [1234567.89012345, -1234567.89012345, 0]
    source.write_bytes(las_header(scale, offset))
    facts = operators._las_quantization(source)
    resolved, selection = operators._resolve_precision({"scale_x": 0.01}, facts, {"min": offset, "max": [v + 1 for v in offset]})
    assert resolved == dict(scale_x=0.01, scale_y=scale[1], scale_z=scale[2], offset_x=offset[0], offset_y=offset[1], offset_z=0)
    assert selection["scale_x"] == "explicit"
    assert selection["offset_x"] == "source"
    assert operators._validated_precision_options({"offset_x": "-2.5", "scale_y": "auto"}) == {"offset_x": -2.5, "scale_y": "auto"}


def test_unquantized_source_uses_numeric_range_without_a_fixed_floor():
    resolved, selection = operators._resolve_precision({}, None, {"min": [0, 6000000.0, -1], "max": [1e-25, 6000000.00001, -1]})
    assert len(resolved) == 6
    assert resolved["scale_x"] < 1e-30
    assert resolved["scale_y"] < 1e-10
    assert resolved["offset_y"] == 6000000
    assert resolved["scale_z"] == 1
    assert resolved["offset_z"] == -1
    assert set(selection.values()) == {"auto"}


