@pytest.mark.parametrize('options', [{'scale_x': 1e-12}, {'scale_x': 'auto', 'offset_x': 1e30}, {'scale_x': 'auto', 'offset_x': -1e30}])
def test_integer_range_is_validated_and_auto_accounts_for_explicit_offset(options):
    bounds = {'min': [0, 0, 0], 'max': [1, 1, 1]}
    if options['scale_x'] != 'auto':
        with pytest.raises(ConverterError) as error:
            operators._resolve_precision(options, None, bounds)
        assert error.value.http_status == 400
    else:
        resolved, selection = operators._resolve_precision(options, None, bounds)
        assert resolved['scale_x'] > 1e20
        assert selection['scale_x'] == 'explicit'


@pytest.mark.parametrize('corruption', ['count', 'scale'])
def test_output_verification_prevents_publication(tmp_path, monkeypatch, corruption):
    source = tmp_path / 'source.xyz'
    source.write_text('1 2 3\n4 5 6\n7 8 9\n')
    target = tmp_path / 'out.copc.laz'
    pdal = tmp_path / 'pdal'
    pdal.write_text('#!/bin/sh\n')
    pdal.chmod(0o755)
    def runner(command, timeout):
        write_native_fixture(command)
        if 'writers.ply' not in command:
            raw = bytearray(Path(command[3]).read_bytes())
            struct.pack_into('<Q' if corruption == 'count' else '<d', raw, 247 if corruption == 'count' else 131, 2 if corruption == 'count' else 0.1)
            Path(command[3]).write_bytes(raw)
        return CommandResult(0)
    def forbidden(*args):
        pytest.fail('unverified output must not be published')
    monkeypatch.setattr(operators, 'publish_target_file', forbidden)
    with pytest.raises(ConverterError, match='verification failed'):
        invoke_operator('xyz_to_copc', {'access_plan': mounted_plan(source, target, 'xyz')}, runner=runner,
                        env={'POINTCLOUD_PDAL_BIN': str(pdal), 'POINTCLOUD_WORK_DIR': str(tmp_path / 'work')})
    assert not target.exists()
    assert not list((tmp_path / 'work').iterdir())


@pytest.mark.parametrize('corruption', ['empty', 'nan', 'truncated', 'count'])
def test_invalid_coordinate_scan_is_rejected_and_deleted(tmp_path, corruption):
    pdal = tmp_path / 'pdal'
    pdal.write_text('#!/bin/sh\n')
    pdal.chmod(0o755)
    def runner(command, timeout):
        write_native_fixture(command)
        path = Path(command[3])
        raw = path.read_bytes()
        if corruption == 'empty':
            raw = raw.replace(b'element vertex 3', b'element vertex 0')[:-72]
        elif corruption == 'nan':
            raw = raw[:-72] + struct.pack('<9d', math.nan, 2, 3, 4, 5, 6, 7, 8, 9)
        elif corruption == 'truncated':
            raw = raw[:-1]
        else:
            raw = raw.replace(b'element vertex 3', b'element vertex 4')
        path.write_bytes(raw)
        return CommandResult(0)
    with pytest.raises(ConverterError):
        operators._scan_coordinate_bounds(str(pdal), 'source.xyz', 'xyz', tmp_path,
                                          runner=runner, env={}, timeout_seconds=5)
    assert not (tmp_path / 'coordinate-bounds.ply').exists()


def test_range_scan_and_conversion_share_timeout_budget(tmp_path, monkeypatch):
    source = tmp_path / 'source.xyz'
    source.write_text('1 2 3\n4 5 6\n7 8 9\n')
    target = tmp_path / 'out.copc.laz'
    pdal = tmp_path / 'pdal'
    pdal.write_text('#!/bin/sh\n')
    pdal.chmod(0o755)
    now = [0]
    monkeypatch.setattr(operators.time, 'monotonic', lambda: now[0])
    def runner(command, timeout):
        assert timeout == 5
        assert 'writers.ply' in command
        write_native_fixture(command)
        now[0] = 6
        return CommandResult(0)
    with pytest.raises(ConverterError) as error:
        invoke_operator('xyz_to_copc', {'access_plan': mounted_plan(source, target, 'xyz')}, runner=runner,
                        env={'POINTCLOUD_PDAL_BIN': str(pdal), 'POINTCLOUD_WORK_DIR': str(tmp_path / 'work')}, timeout_seconds=5)
    assert error.value.error_code == 'CONVERSION_TIMEOUT'
    assert not target.exists()
    assert not list((tmp_path / 'work').iterdir())
