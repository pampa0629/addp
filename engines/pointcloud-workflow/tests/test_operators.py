def las_header(scale=(0.001, 0.002, 0.003), offset=(1.0, 2.0, 3.0), count=3):
    header = bytearray(375)
    header[:4] = b"LASF"
    header[24:26] = bytes([1, 4])
    struct.pack_into("<3d", header, 131, *scale)
    struct.pack_into("<3d", header, 155, *offset)
    struct.pack_into("<Q", header, 247, count)
    return bytes(header)


def write_native_fixture(command):
    path = Path(command[3])
    if "writers.ply" in command:
        header = b"ply\nformat binary_little_endian 1.0\ncomment Generated by PDAL\nelement vertex 3\nproperty float64 x\nproperty float64 y\nproperty float64 z\nend_header\n"
        path.write_bytes(header + struct.pack("<9d", 1, 2, 3, 4, 5, 6, 7, 8, 9))
    else:
        values = dict(arg.removeprefix("--writers.copc.").split("=", 1) for arg in command if arg.startswith("--writers.copc."))
        path.write_bytes(las_header([float(values[f"scale_{a}"]) for a in "xyz"], [float(values[f"offset_{a}"]) for a in "xyz"]))

def mounted_plan(source: Path, target: Path, source_format: str):
    return {
        "schema_version": "addp.workflow.access-plan/v1",
        "source": {
            "kind": "file",
            "format": source_format,
            "access": {"method": "mounted_path", "path": str(source)},
            "metadata": {"source_size_bytes": source.stat().st_size},
        },
        "target": {
            "kind": "file",
            "format": "copc",
            "name": target.name,
            "write_mode": "create",
            "content_type": "application/vnd.laszip+copc",
            "access": {"method": "mounted_path", "path": str(target)},
        },
    }


