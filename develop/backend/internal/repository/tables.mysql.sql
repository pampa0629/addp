CREATE TABLE IF NOT EXISTS catalog_resource_changes (
    `id` bigint NOT NULL AUTO_INCREMENT,
    `tenant_id` bigint NOT NULL,
    `source_type` varchar(32) NOT NULL,
    `source_identity` bigint NOT NULL,
    `operation` varchar(16) NOT NULL,
    `snapshot` json NOT NULL,
    `observed_at` datetime(6) NOT NULL,
    PRIMARY KEY (id),
    KEY idx_develop_catalog_changes_source (tenant_id, source_type, source_identity),
    KEY idx_develop_catalog_changes_tenant_id (tenant_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS dev_tasks (
    `id` bigint NOT NULL AUTO_INCREMENT,
    `tenant_id` bigint NOT NULL,
    `name` varchar(255) NOT NULL,
    `display_name` varchar(255),
    `dev_type` varchar(50) NOT NULL,
    `content` json NOT NULL,
    `execution_config` json,
    `editor_layout` json DEFAULT ('{}') NOT NULL,
    `timeout` bigint DEFAULT 300,
    `description` longtext,
    `tags` json,
    `created_by` bigint,
    `updated_by` bigint,
    `created_at` datetime(6),
    `updated_at` datetime(6),
    `deleted_at` datetime(6),
    `status` varchar(50) DEFAULT 'active',
    `last_execution_id` varchar(36),
    `last_execution_status` varchar(50),
    `last_run_at` datetime(6),
    PRIMARY KEY (id),
    KEY idx_dev_tasks_status (status),
    KEY idx_dev_tasks_tenant_type (tenant_id, dev_type),
    KEY idx_develop_dev_tasks_deleted_at (deleted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS execution_policy (
    `id` bigint NOT NULL AUTO_INCREMENT,
    `scope_type` varchar(32) NOT NULL,
    `tenant_id` bigint,
    `default_query_timeout` bigint NOT NULL,
    `max_query_timeout` bigint NOT NULL,
    `query_result_limit` bigint NOT NULL,
    `query_concurrency` bigint DEFAULT 20 NOT NULL,
    `query_per_engine_concurrency` bigint DEFAULT 5 NOT NULL,
    `workflow_concurrency` bigint DEFAULT 2 NOT NULL,
    `notebook_concurrency` bigint DEFAULT 1 NOT NULL,
    `version` bigint NOT NULL,
    `updated_by` bigint NOT NULL,
    `created_at` datetime(6),
    `updated_at` datetime(6),
    PRIMARY KEY (id),
    UNIQUE KEY idx_develop_execution_policy_scope (scope_type, tenant_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS file_executions (
    `execution_id` varchar(64) NOT NULL,
    `tenant_id` bigint NOT NULL,
    `actor_principal_id` bigint NOT NULL,
    `actor_membership_id` bigint NOT NULL,
    `authorization_version` bigint NOT NULL,
    `config_json` json NOT NULL,
    `intent_json` json NOT NULL,
    `issued_authorization_json` json,
    `admission_state` varchar(16) NOT NULL,
    `admission_json` json,
    `runtime_execution_id` varchar(64),
    `runtime_manifest_json` json,
    `source_read_proofs_json` json,
    `publication_json` json,
    `input_owner_instance_id` longtext,
    `input_directory` longtext,
    `admission_expires_at` datetime(6),
    `version` bigint NOT NULL,
    `created_at` datetime(6),
    `updated_at` datetime(6),
    PRIMARY KEY (execution_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS tool_approvals (
    `id` char(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
    `user_id` bigint NOT NULL,
    `tenant_id` bigint NOT NULL,
    `agent_run_id` varchar(100) NOT NULL,
    `tool_call_id` varchar(100) NOT NULL,
    `tool_name` varchar(100) NOT NULL,
    `request_fingerprint` character(64) NOT NULL,
    `request_payload` json NOT NULL,
    `request_summary` json NOT NULL,
    `status` varchar(20) NOT NULL,
    `requested_at` datetime(6) NOT NULL,
    `expires_at` datetime(6) NOT NULL,
    `decided_at` datetime(6),
    `decided_by_user_id` bigint,
    `consumed_at` datetime(6),
    `execution_id` varchar(100),
    PRIMARY KEY (id),
    KEY idx_develop_tool_approvals_agent_run_id (agent_run_id),
    KEY idx_develop_tool_approvals_expires_at (expires_at),
    KEY idx_develop_tool_approvals_request_fingerprint (request_fingerprint),
    KEY idx_develop_tool_approvals_status (status),
    KEY idx_develop_tool_approvals_tenant_id (tenant_id),
    KEY idx_develop_tool_approvals_user_id (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
