 await expect(page.getByTestId('cdc-task-capture')).toContainText('RUNNING')
 await expect(page.getByTestId('cdc-task-lag')).toHaveText('3')
 await expect(page.getByTestId('cdc-task-committed')).toHaveText('9')
 expect(state.calls.find(c=>c.path.endsWith('/task-definitions')).params).toMatchObject({change_detection:'cdc',runtime_boundary:'continuous',page:'1',page_size:'20'})
 expect(state.calls.some(c=>c.path.includes('/platform/'))).toBe(false)
 await page.setViewportSize({width:390,height:844})
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 if(!en)await page.screenshot({path:'/tmp/addp-cdc-task-chain-mobile.png',fullPage:true})
 await expect(page.getByRole('tab',{name:en?'Runtime resources':'运行资源',exact:true})).toHaveCount(0)
 await expect(page.getByRole('tab',{name:en?'Task chain':'任务链路',exact:true})).toBeVisible()
 await page.goto('/cdc-resources?view=resources')
 await expect(page.getByText(en?'Runtime resources belong to the platform. Switch to the platform context to view them':'运行资源属于平台，请切换到平台身份查看')).toBeVisible()
 const count=state.calls.length;await page.waitForTimeout(50);expect(state.calls.length).toBe(count)
 await page.getByRole('tab',{name:en?'Task chain':'任务链路',exact:true}).click()
 await expect(page.getByTestId('cdc-task-chain')).toBeVisible()
