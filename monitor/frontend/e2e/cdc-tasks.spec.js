test('CDC rejects foreign execution, clears values on denial and pauses hidden refresh',async({page})=>{
 const state=await cdcTaskBackend(page)
 await page.clock.install();await page.goto('/cdc-resources?view=tasks&task_id=7')
 await expect(page.getByTestId('cdc-task-lag')).toHaveText('3')
 await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'))})
 const count=state.calls.length;await page.clock.fastForward(60001);expect(state.calls.length).toBe(count)
 state.setMode('foreign');await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:false});document.dispatchEvent(new Event('visibilitychange'))})
 await expect(page.getByTestId('cdc-task-execution-error')).toBeVisible();await expect(page.getByTestId('cdc-task-lag')).toHaveCount(0)
 state.setMode('denied');await page.clock.fastForward(15001)
 await expect(page.getByTestId('cdc-task-error')).toBeVisible();await expect(page.getByTestId('cdc-task-source')).toHaveCount(0)
 const denied=state.calls.length;await page.clock.fastForward(60001);expect(state.calls.length).toBe(denied)
})
