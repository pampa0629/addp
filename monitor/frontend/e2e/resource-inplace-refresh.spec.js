import { test, expect } from '@playwright/test'
import { resourceBackend, node, identity, setIdentity, completeComparisonTrend } from './node-resources.fixture'
import { backend as processBackend } from './process-resources.fixture'

const refreshButton = page => page.getByRole('button', { name: '刷新', exact: true }).first()
const nextStamp = '2026-10-07T00:00:15Z'

for (const automatic of [false, true]) test(`host list ${automatic ? 'automatic' : 'manual'} refresh keeps rows, summaries and pagination visible`, async ({ page }) => {
  const state = await resourceBackend(page)
  if (automatic) await page.clock.install()
  await page.goto(`/node-resources?refresh=${automatic ? '60' : 'off'}`)
  const list = page.getByTestId('resource-node-list')
  await expect(list).toContainText('16.00 GiB')
  const reads = () => state.reads.filter(read => read.path.endsWith('resource_summaries')).length
  const before = reads(), row = await list.locator('.el-table__body tr').first().elementHandle()
  state.holdSummary()
  if (automatic) await page.clock.fastForward(60001)
  else await refreshButton(page).click()
  await expect.poll(reads).toBe(before + 1)
  await expect(list).toContainText('16.00 GiB')
  await expect(page.locator('.resource-pagination').first()).toBeVisible()
  await expect(list.locator('.el-loading-mask')).toHaveCount(0)
  expect(await row.evaluate(el => el.isConnected)).toBe(true)
  state.releaseSummary()
  await expect(refreshButton(page)).toBeEnabled()
})

for (const automatic of [false, true]) test(`host detail ${automatic ? 'automatic' : 'manual'} refresh retains comparison, devices and the same chart until new trend arrives`, async ({ page }) => {
  const state = await resourceBackend(page, { trendResponse: completeComparisonTrend })
  if (automatic) await page.clock.install()
  await page.goto(`/node-resources/${node}?range=5m&compare=previous&refresh=${automatic ? '60' : 'off'}`)
  const chart = page.getByTestId('resource-chart').locator('canvas')
  await expect(chart).toBeVisible()
  await expect(refreshButton(page)).toBeEnabled()
  const canvas = await chart.elementHandle()
  const reads = () => state.reads.filter(read => read.path.endsWith('resource_trends')).length
  const before = reads()
  const filesystem = page.getByTestId('resource-filesystem-table')
  const table = await filesystem.elementHandle()
  state.holdTrend(); state.serverEnd = nextStamp
  if (automatic) await page.clock.fastForward(60001)
  else await refreshButton(page).click()
  await expect.poll(reads).toBe(before + 1)
  await expect(page.getByTestId('resource-memoryTotal')).toContainText('16.00 GiB')
  await expect(page.getByTestId('resource-comparison')).toBeVisible()
  expect(await canvas.evaluate(el => el.isConnected)).toBe(true)
  expect(await table.evaluate(el => el.isConnected)).toBe(true)
  await expect(filesystem).toContainText('/data')
  state.releaseTrend()
  await expect(refreshButton(page)).toBeEnabled()
  await expect(page.getByTestId('resource-trend-window')).toContainText(':00:15')
  expect(await canvas.evaluate(el => el.isConnected)).toBe(true)
})

