import { expect, test } from '@playwright/test'
import { tmpdir } from 'node:os'
import { mkdtempSync } from 'node:fs'
import { join } from 'node:path'
import { fixture, resourceIncident } from './platform-alerts.fixture'
import { identity, setIdentity, localTimeInput } from './monitoring-targets.fixture'

const keys = ['monitor.platform_alert.read', 'monitor.platform_alert_notification.read', 'platform.host_node.read']
const reads = state => state.requests.filter(request => request.path.endsWith('/alerts'))
const entries = Array.from({ length: 23 }, (_, index) => ({ ...resourceIncident, id: index + 100, name: 'CPU alert', status: 'open', opened_at: '2026-10-24T00:00:00Z' }))

for (const locale of ['zh-cn', 'en']) test(`alert filters debounce, merge immediate selections and show local tips (${locale})`, async ({ page }) => {
  await page.clock.install()
  const state = await fixture(page, { locale, keys, entries, hostNames: { [resourceIncident.subject_id]: 'Host One' }, path: '/platform-alerts?page=2&category=resource&severity=warning' })
  const table = page.getByTestId('pipeline-incidents'), form = page.getByTestId('alert-filters')
  await expect(table.locator('tbody > tr.el-table__row')).toHaveCount(3)
  await page.clock.pauseAt(await page.evaluate(() => Date.now() + 1000))
  await expect(form.getByRole('button', { name: locale === 'en' ? 'Search' : '搜索', exact: true })).toHaveCount(0)
  const name = form.getByRole('textbox', { name: locale === 'en' ? 'Alert name' : '告警名称', exact: true })
  await name.fill('C'); await name.fill('CPU')
  expect(reads(state)).toHaveLength(1)
  await page.clock.fastForward(299); expect(reads(state)).toHaveLength(1)
  await page.clock.fastForward(1)
  await expect.poll(() => reads(state).length).toBe(2)
  expect(reads(state).at(-1).query).toMatchObject({ search: 'CPU', category: 'resource', severity: 'warning', page: '1' })
  await expect(table.locator('tbody > tr.el-table__row')).toHaveCount(20)
  const subject = form.getByRole('textbox', { name: locale === 'en' ? 'Source subject ID' : '来源主体 ID', exact: true })
  await subject.fill(resourceIncident.subject_id); await subject.press('Enter')
  await expect.poll(() => reads(state).length).toBe(3)
  await subject.hover(); await subject.locator('..').locator('.el-input__clear').click()
  await expect.poll(() => reads(state).length).toBe(4)
  const host = form.getByRole('textbox', { name: locale === 'en' ? 'Host name' : '主机名称', exact: true })
  await host.fill('Host')
  await form.locator('.el-select').filter({ has: page.getByRole('combobox', { name: locale === 'en' ? 'Status' : '状态', exact: true }) }).click()
  await page.clock.runFor(200)
  await page.getByRole('option', { name: locale === 'en' ? 'All statuses' : '全部状态', exact: true }).click()
  await expect.poll(() => reads(state).length).toBe(5)
  expect(reads(state).at(-1).query).toMatchObject({ search: 'CPU', host_name: 'Host' })
  expect(reads(state).at(-1).query).not.toHaveProperty('status')
  await page.clock.fastForward(301); expect(reads(state)).toHaveLength(5)
  const hostHint = locale === 'en' ? 'Matches current names for host resource alerts only.' : '按当前名称匹配，仅查询主机资源告警。'
  await form.locator('.alert-host-filter .field-help').hover(); await page.clock.runFor(160)
  await expect(page.getByRole('tooltip', { name: hostHint, exact: true })).toBeVisible()
  await page.mouse.move(0, 0)
  await form.locator('.alert-time-filter .field-help').focus(); await page.clock.runFor(160)
  await expect(page.getByRole('tooltip', { name: locale === 'en' ? /Filter by first opening time/ : /按首次发现时间查询/ })).toBeVisible()
  await name.focus(); await page.clock.runFor(200)
  await page.setViewportSize({ width: 620, height: 900 }); await page.clock.runFor(350)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const path = join(mkdtempSync(join(tmpdir(), 'addp-alert-filters-')), `${locale}.png`)
  await page.screenshot({ path, fullPage: true, animations: 'disabled' }); console.log(`Alert filter screenshot: ${path}`)
})

test('hidden pending alert text resumes once and tab refresh or identity changes cancel old text', async ({ page }) => {
  await page.clock.install()
  const state = await fixture(page)
  await expect(page.getByTestId('pipeline-incidents')).toBeVisible()
  await page.clock.pauseAt(await page.evaluate(() => Date.now() + 1000))
  const input = page.getByRole('textbox', { name: '告警名称', exact: true })
  const visibility = hidden => page.evaluate(hidden => { Object.defineProperty(document, 'hidden', { configurable: true, value: hidden }); document.dispatchEvent(new Event('visibilitychange')) }, hidden)
  await input.fill('queued'); await visibility(true); await page.clock.fastForward(1000)
  expect(reads(state)).toHaveLength(1)
  await visibility(false); await page.clock.fastForward(301)
  await expect.poll(() => reads(state).length).toBe(2)
  await input.fill('stale tab')
  await page.getByRole('button', { name: '通知管理', exact: true }).click()
  await page.clock.fastForward(301); expect(reads(state)).toHaveLength(2)
  await page.getByRole('button', { name: '告警事件', exact: true }).click()
  await expect.poll(() => reads(state).length).toBe(3)
  await expect(input).toHaveValue('queued')
  await input.fill('stale refresh')
  await page.getByRole('button', { name: '刷新', exact: true }).click()
  await expect.poll(() => reads(state).length).toBe(4)
  await page.clock.fastForward(301); expect(reads(state)).toHaveLength(4)
  await expect(input).toHaveValue('queued')
  await input.fill('forbidden')
  await setIdentity(page, identity([])); await page.clock.fastForward(1000)
  expect(reads(state)).toHaveLength(4)
  await expect(input).toHaveCount(0)
})

test('invalid route time survives unrelated text and other-bound edits until explicitly corrected', async ({ page }) => {
  const state = await fixture(page, { path: '/platform-alerts?severity=warning&time_from=invalid' })
  await expect(page.getByText('Invalid opening time range', { exact: true })).toBeVisible()
  const name = page.getByRole('textbox', { name: '告警名称', exact: true })
  await name.fill('CPU'); await name.press('Enter')
  const to = page.getByPlaceholder('结束时间')
  await to.fill(await localTimeInput(page, '2026-10-25T00:00:00Z')); await to.press('Tab')
  await expect(page.getByRole('status')).toContainText('起始时间须早于结束时间')
  expect(reads(state)).toHaveLength(1)
  expect(new URL(page.url()).searchParams.get('time_from')).toBe('invalid')
  const from = page.getByPlaceholder('起始时间')
  await from.fill(await localTimeInput(page, '2026-10-24T00:00:00Z')); await from.press('Tab')
  await expect.poll(() => reads(state).length).toBe(2)
  expect(reads(state).at(-1).query).toMatchObject({ search: 'CPU', severity: 'warning', time_from: '2026-10-24T00:00:00.000Z', time_to: '2026-10-25T00:00:00.000Z' })
})

test('reversed time keeps all draft filters unsubmitted and correction applies the complete scope', async ({ page }) => {
  const state = await fixture(page, { path: '/platform-alerts?time_from=2026-10-02T00:00:00Z&time_to=2026-10-03T00:00:00Z' })
  await expect(page.getByTestId('pipeline-incidents')).toBeVisible()
  const to = page.getByPlaceholder('结束时间')
  await to.fill(await localTimeInput(page, '2026-10-01T00:00:00Z')); await to.press('Tab')
  await expect(page.getByRole('status')).toContainText('起始时间须早于结束时间')
  await page.getByRole('textbox', { name: '告警名称', exact: true }).fill('CPU')
  await page.locator('.el-select').filter({ has: page.getByRole('combobox', { name: '状态', exact: true }) }).click()
  await page.getByRole('option', { name: '已恢复', exact: true }).click()
  expect(reads(state)).toHaveLength(1)
  await to.fill(await localTimeInput(page, '2026-10-04T00:00:00Z')); await to.press('Tab')
  await expect.poll(() => reads(state).length).toBe(2)
  expect(reads(state).at(-1).query).toMatchObject({ search: 'CPU', status: 'resolved', time_from: '2026-10-02T00:00:00.000Z', time_to: '2026-10-04T00:00:00.000Z' })
})
