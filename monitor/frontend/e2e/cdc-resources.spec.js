test('CDC has independent component permission and clears stale values after denial', async ({ page }) => {
  const state = await cdcBackend(page, { permissions: ['monitor.resource_observation.read'] })
  await page.clock.install(); await page.goto('/cdc-resources')
  await expect(page.getByTestId('cdc-value-connectors')).toHaveText('2')
  await expect(page.getByTestId('cdc-card-postgresql')).toHaveCount(0)
  await expect(page.getByTestId('cdc-open-workers')).toHaveCount(0)
  expect(state.calls.some(path => path.includes('engine_'))).toBe(false)
  const visibility = hidden => page.evaluate(hidden => { Object.defineProperty(document, 'hidden', { configurable: true, value: hidden }); document.dispatchEvent(new Event('visibilitychange')) }, hidden)
  await expect(page.locator('.cdc-resources')).toHaveAttribute('aria-busy', 'false')
  await visibility(true); const count = state.calls.length; await page.clock.fastForward(60001); expect(state.calls.length).toBe(count)
  state.holdTrend(); state.setMode('failed'); await visibility(false)
  await expect(page.getByTestId('cdc-value-connectors')).toHaveText('—')
  await expect(page.locator('.cdc-resources')).toHaveAttribute('aria-busy', 'true')
  await expect.poll(() => state.calls.filter(path => path.endsWith('/cdc_resource_trends')).length).toBe(2)
  const inFlight = state.calls.length
  await page.clock.fastForward(15001); expect(state.calls.length).toBe(inFlight)
  state.releaseTrend()
  await expect(page.locator('.cdc-resources')).toHaveAttribute('aria-busy', 'false')
  state.setMode('denied'); await page.clock.fastForward(15001)
  await expect(page.getByTestId('cdc-error')).toBeVisible()
  await expect(page.getByTestId('cdc-value-sourceDelay')).toHaveText('—')
  await expect(page.getByTestId('cdc-trend')).toHaveCount(0)
  await expect(page.getByTestId('cdc-refresh-status')).toContainText('自动刷新已停止')
  const denied = state.calls.length; await page.clock.fastForward(60001); expect(state.calls.length).toBe(denied)
})
test('CDC cancels late responses after scope changes and preserves cards during same-context refresh', async ({ page }) => {
  const state = await cdcBackend(page)
  await page.goto('/cdc-resources?refresh=off')
  await expect(page.getByTestId('cdc-value-failedTasks')).toHaveText('1')
  await expect(page.locator('.cdc-resources')).toHaveAttribute('aria-busy', 'false')
  state.hold()
  await page.getByRole('button', { name: '刷新', exact: true }).click()
  await expect(page.locator('.cdc-resources')).toHaveAttribute('aria-busy', 'true')
  await expect(page.getByTestId('cdc-value-failedTasks')).toHaveText('1')
  await page.goto('/cdc-resources?stage=redpanda&refresh=off')
  state.setMode('foreign'); state.release()
  await page.getByRole('button', { name: '刷新', exact: true }).click()
  await expect(page.getByTestId('cdc-error')).toBeVisible()
  await expect(page.getByTestId('cdc-value-failedTasks')).toHaveText('—')
})

test('CDC Platform hides Tenant entry and preserves explicit history without cross-domain requests', async ({ page }) => {
  const state = await cdcBackend(page)
  await page.goto('/cdc-resources?view=tasks')
  await expect(page.getByText('任务链路属于租户，请切换到目标租户身份查看')).toBeVisible()
  expect(state.calls).toEqual([])
  await page.getByRole('tab', { name: '运行资源', exact: true }).click()
  await expect(page.getByTestId('cdc-card-kafka-connect')).toBeVisible()
  expect(state.calls.some(path => path.includes('/transfer/'))).toBe(false)
  await page.goBack()
  await expect(page.getByText('任务链路属于租户，请切换到目标租户身份查看')).toBeVisible()
  await expect(page).toHaveURL(/view=tasks$/)
  await expect(page.getByTestId('cdc-card-kafka-connect')).toHaveCount(0)
  await expect(page.getByRole('tab', { name: '任务链路', exact: true })).toHaveCount(0)
})

