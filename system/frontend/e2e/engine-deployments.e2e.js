async function selectHost(page){
 await page.getByRole('dialog').getByRole('combobox',{name:'承载主机',exact:true}).press('Enter')
 await page.getByRole('option',{name:'Node A',exact:true}).click()
}
async function discoveryTab(page,name){
 await page.getByTestId('deployment-discovery-scopes').getByRole('tab',{name,exact:true}).click()
}
const candidate = (page, name) => page.getByTestId('deployment-candidates').getByRole('checkbox', { name, exact: true })
const toggle = (page, name) => candidate(page, name).locator('..').click()
async function selectSources(page, services = ['postgres']) {
 for (const [scope, label] of [['infra', 'Infra 基础设施'], ['business', 'Business 业务引擎']]) {
  await discoveryTab(page, label)
  for (const service of services) await toggle(page, `${scope} ${service}`)
 }
}
