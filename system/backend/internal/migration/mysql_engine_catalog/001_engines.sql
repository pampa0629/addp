CREATE TABLE IF NOT EXISTS engines (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_id BIGINT,
    name VARCHAR(255) NOT NULL,
    engine_type LONGTEXT NOT NULL,
    engine_origin LONGTEXT NOT NULL DEFAULT ('general'),
    connection_info JSON NOT NULL,
    description LONGTEXT,
    created_by BIGINT,
    is_builtin BOOLEAN DEFAULT FALSE,
    capabilities JSON,
    connection_status VARCHAR(20) DEFAULT 'unknown',
    last_check_at DATETIME(6),
    check_message LONGTEXT,
    created_at DATETIME(6),
    updated_at DATETIME(6),
    lifecycle_state VARCHAR(20) NOT NULL DEFAULT 'active',
    deletion_scan_task_id VARCHAR(64),
    deletion_execute_task_id VARCHAR(64),
    deletion_error LONGTEXT,
    deletion_requested_at DATETIME(6),
    deletion_requested_by BIGINT,
    external_artifact_policy VARCHAR(20) NOT NULL DEFAULT 'delete',
    identity_key JSON NOT NULL,
    version BIGINT NOT NULL DEFAULT 1,
    deleted_at DATETIME(6),
    deleted_by BIGINT,
    restored_at DATETIME(6),
    restored_by BIGINT,
    server_version LONGTEXT NOT NULL DEFAULT (''),
    server_version_checked_at DATETIME(6),
    active_address BINARY(32) GENERATED ALWAYS AS (
        IF(lifecycle_state = 'deleted', NULL,
            UNHEX(SHA2(CAST(JSON_ARRAY(tenant_id, LOWER(engine_type), identity_key) AS CHAR CHARACTER SET utf8mb4), 256)))
    ) STORED,
    CONSTRAINT ck_engines_version_positive CHECK (version > 0),
    CONSTRAINT ck_engines_lifecycle_state CHECK (lifecycle_state IN ('active','disabled','deleting','deleted')),
    UNIQUE KEY idx_engines_tenant_engine_unique (tenant_id, id),
    UNIQUE KEY uq_engines_active_address (active_address),
    KEY idx_engines_connection_status (connection_status),
    KEY idx_engines_engine_type (engine_type(128)),
    KEY idx_engines_is_builtin (is_builtin),
    KEY idx_engines_lifecycle_state (lifecycle_state),
    KEY idx_engines_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin
