CREATE TABLE IF NOT EXISTS mfa_challenges (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    token_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
    principal_id BIGINT NOT NULL,
    purpose VARCHAR(16) NOT NULL,
    source_family_id BIGINT,
    issued_authorization_version BIGINT NOT NULL,
    authentication_methods JSON NOT NULL,
    authenticated_at DATETIME(6) NOT NULL,
    expires_at DATETIME(6) NOT NULL,
    failed_attempts INT NOT NULL DEFAULT 0,
    consumed_at DATETIME(6),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    KEY idx_mfa_challenges_principal_created_at (principal_id, created_at DESC),
    KEY idx_mfa_challenges_source_family_pending (source_family_id, consumed_at),
    KEY idx_mfa_challenges_expires_at (consumed_at, expires_at),
    FOREIGN KEY (principal_id) REFERENCES users (id),
    FOREIGN KEY (source_family_id) REFERENCES refresh_token_families (id),
    CHECK (REGEXP_LIKE(token_hash, '^[0-9a-f]{64}$', 'c')),
    CHECK (issued_authorization_version > 0),
    CHECK ((purpose='login' AND source_family_id IS NULL) OR (purpose='step_up' AND source_family_id IS NOT NULL)),
    CHECK (authentication_methods = JSON_ARRAY('password')),
    CHECK (failed_attempts BETWEEN 0 AND 5),
    CHECK (authenticated_at <= created_at AND expires_at > created_at AND (consumed_at IS NULL OR consumed_at >= created_at))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin
