CREATE TABLE IF NOT EXISTS context_selection_tickets (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    token_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
    principal_id BIGINT NOT NULL,
    issued_authorization_version BIGINT NOT NULL,
    client_id VARCHAR(16) NOT NULL DEFAULT 'addp-web',
    authentication_methods JSON NOT NULL,
    assurance_level VARCHAR(16) NOT NULL,
    authenticated_at DATETIME(6) NOT NULL,
    step_up_expires_at DATETIME(6),
    expires_at DATETIME(6) NOT NULL,
    consumed_at DATETIME(6),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    KEY idx_selection_principal_pending (principal_id, consumed_at, expires_at),
    KEY idx_selection_pending_expiry (consumed_at, expires_at),
    FOREIGN KEY (principal_id) REFERENCES principals (id),
    CHECK (REGEXP_LIKE(token_hash, '^[0-9a-f]{64}$', 'c')),
    CHECK (issued_authorization_version > 0 AND client_id = 'addp-web'),
    CHECK (assurance_level IN ('aal1','aal2','aal3')),
    CHECK (JSON_SCHEMA_VALID('{"type":"array","minItems":1,"uniqueItems":true,"items":{"type":"string","pattern":"[^ ]"}}', authentication_methods)),
    CHECK (authenticated_at <= created_at AND expires_at > created_at),
    CHECK (consumed_at IS NULL OR consumed_at BETWEEN created_at AND expires_at),
    CHECK (step_up_expires_at IS NULL OR step_up_expires_at >= authenticated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin
