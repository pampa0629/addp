CREATE TABLE IF NOT EXISTS notebook_session_authorizations (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    session_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
    task_id BIGINT NOT NULL CHECK (task_id>0),
    actor_principal_id BIGINT NOT NULL,
    tenant_id BIGINT NOT NULL,
    tenant_membership_id BIGINT NOT NULL,
    token_family_id BIGINT NOT NULL,
    issued_authorization_version BIGINT NOT NULL CHECK (issued_authorization_version>0),
    audience VARCHAR(16) NOT NULL CHECK (audience='develop'),
    operations JSON NOT NULL CHECK (operations=JSON_ARRAY('catalog.list_children','execution_engine_access.derive')),
    expires_at DATETIME(6) NOT NULL,
    revoked_at DATETIME(6),
    revoked_reason TEXT,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CHECK (REGEXP_LIKE(id,'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$','c')),
    CHECK (REGEXP_LIKE(session_id,'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$','c')),
    CHECK (expires_at>created_at AND expires_at<=created_at+INTERVAL 1 HOUR),
    CHECK ((revoked_at IS NULL AND revoked_reason IS NULL) OR
           (revoked_at>=created_at AND revoked_at IS NOT NULL AND revoked_reason IS NOT NULL AND TRIM(revoked_reason)<>'')),
    FOREIGN KEY (actor_principal_id) REFERENCES principals(id),
    FOREIGN KEY (tenant_id) REFERENCES tenants(id),
    FOREIGN KEY (tenant_membership_id) REFERENCES tenant_memberships(id),
    FOREIGN KEY (token_family_id) REFERENCES refresh_token_families(id),
    INDEX(actor_principal_id,tenant_id,revoked_at,expires_at),
    INDEX(tenant_membership_id,revoked_at,expires_at),
    INDEX(token_family_id,revoked_at,expires_at),
    INDEX(revoked_at,expires_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin
