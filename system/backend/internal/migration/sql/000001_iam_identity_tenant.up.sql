BEFORE UPDATE ON system.principals
FOR EACH ROW EXECUTE FUNCTION system.set_updated_at();
CREATE TRIGGER trg_users_updated_at
BEFORE UPDATE ON system.users
FOR EACH ROW EXECUTE FUNCTION system.set_updated_at();
CREATE TRIGGER trg_local_accounts_updated_at
BEFORE UPDATE ON system.local_accounts
FOR EACH ROW EXECUTE FUNCTION system.set_updated_at();
CREATE TRIGGER trg_tenants_updated_at
BEFORE UPDATE ON system.tenants
FOR EACH ROW EXECUTE FUNCTION system.set_updated_at();
CREATE TRIGGER trg_tenant_memberships_updated_at
BEFORE UPDATE ON system.tenant_memberships
FOR EACH ROW EXECUTE FUNCTION system.set_updated_at();
CREATE TRIGGER trg_service_principals_updated_at
BEFORE UPDATE ON system.service_principals
FOR EACH ROW EXECUTE FUNCTION system.set_updated_at();

