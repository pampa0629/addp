CREATE FUNCTION system.bump_organization_membership_authorization_version()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    affected_tenant_membership_id bigint;
BEGIN
    IF TG_OP = 'DELETE' THEN
        affected_tenant_membership_id := OLD.tenant_membership_id;
    ELSE
        affected_tenant_membership_id := NEW.tenant_membership_id;
    END IF;

    UPDATE system.principals p
    SET authorization_version = p.authorization_version + 1,
        updated_at = now()
    FROM system.tenant_memberships tm
    WHERE tm.id = affected_tenant_membership_id
      AND p.id = tm.principal_id;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.bump_department_members_authorization_version()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.status = 'disabled' AND OLD.status <> 'disabled' THEN
        PERFORM 1
        FROM system.principals p
        WHERE EXISTS (
            SELECT 1
            FROM system.tenant_memberships tm
            JOIN system.department_memberships dm ON dm.tenant_membership_id = tm.id
            WHERE dm.department_id = NEW.id
              AND dm.status = 'active'
              AND p.id = tm.principal_id
        )
        ORDER BY p.id
        FOR UPDATE;

        UPDATE system.principals p
        SET authorization_version = p.authorization_version + 1,
            updated_at = now()
        FROM system.tenant_memberships tm
        JOIN system.department_memberships dm ON dm.tenant_membership_id = tm.id
        WHERE dm.department_id = NEW.id
          AND dm.status = 'active'
          AND p.id = tm.principal_id;
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.bump_project_group_members_authorization_version()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.status = 'closed' AND OLD.status <> 'closed' THEN
        PERFORM 1
        FROM system.principals p
        WHERE EXISTS (
            SELECT 1
            FROM system.tenant_memberships tm
            JOIN system.project_group_memberships pgm ON pgm.tenant_membership_id = tm.id
            WHERE pgm.project_group_id = NEW.id
              AND pgm.status = 'active'
              AND p.id = tm.principal_id
        )
        ORDER BY p.id
        FOR UPDATE;

        UPDATE system.principals p
        SET authorization_version = p.authorization_version + 1,
            updated_at = now()
        FROM system.tenant_memberships tm
        JOIN system.project_group_memberships pgm ON pgm.tenant_membership_id = tm.id
        WHERE pgm.project_group_id = NEW.id
          AND pgm.status = 'active'
          AND p.id = tm.principal_id;
    END IF;
    RETURN NEW;
END;
$$;

