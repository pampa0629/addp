CREATE TABLE system.identity_providers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issuer text NOT NULL UNIQUE CHECK (btrim(issuer) <> ''),
    protocol text NOT NULL CHECK (protocol IN ('oidc', 'saml')),
    display_name text NOT NULL CHECK (btrim(display_name) <> ''),
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE system.tenant_idp_connections (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL REFERENCES system.tenants(id),
    identity_provider_id bigint NOT NULL REFERENCES system.identity_providers(id),
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    provisioning_mode text NOT NULL CHECK (provisioning_mode IN ('preprovisioned', 'jit')),
    mapping_version bigint NOT NULL DEFAULT 1 CHECK (mapping_version > 0),
    secret_ref text CHECK (secret_ref IS NULL OR btrim(secret_ref) <> ''),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, identity_provider_id),
    UNIQUE (tenant_id, id)
);

CREATE INDEX idx_tenant_idp_connections_identity_provider
    ON system.tenant_idp_connections (identity_provider_id);

CREATE TABLE system.external_identities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identity_provider_id bigint NOT NULL REFERENCES system.identity_providers(id),
    subject text NOT NULL CHECK (btrim(subject) <> ''),
    user_id bigint NOT NULL REFERENCES system.users(id),
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled', 'unlinked')),
    last_authenticated_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (identity_provider_id, subject)
);

CREATE INDEX idx_external_identities_user
    ON system.external_identities (user_id);

CREATE TABLE system.user_attribute_authorities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES system.users(id),
    attribute_name text NOT NULL CHECK (btrim(attribute_name) <> ''),
    authority_type text NOT NULL CHECK (authority_type IN ('local', 'identity_provider', 'directory_sync')),
    tenant_idp_connection_id bigint REFERENCES system.tenant_idp_connections(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, attribute_name),
    CHECK (
        (authority_type = 'local' AND tenant_idp_connection_id IS NULL)
        OR (authority_type IN ('identity_provider', 'directory_sync') AND tenant_idp_connection_id IS NOT NULL)
    )
);

CREATE INDEX idx_user_attribute_authorities_connection
    ON system.user_attribute_authorities (tenant_idp_connection_id)
    WHERE tenant_idp_connection_id IS NOT NULL;

CREATE TABLE system.departments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL REFERENCES system.tenants(id),
    parent_id bigint,
    code text NOT NULL CHECK (code = lower(btrim(code)) AND code <> ''),
    name text NOT NULL CHECK (btrim(name) <> ''),
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, code),
    UNIQUE (tenant_id, id),
    FOREIGN KEY (tenant_id, parent_id) REFERENCES system.departments (tenant_id, id),
    CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE INDEX idx_departments_tenant_parent
    ON system.departments (tenant_id, parent_id)
    WHERE parent_id IS NOT NULL;

CREATE TABLE system.department_memberships (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    department_id bigint NOT NULL,
    tenant_membership_id bigint NOT NULL,
    membership_type text NOT NULL CHECK (membership_type IN ('primary', 'additional')),
    relation_role text NOT NULL DEFAULT 'member' CHECK (relation_role IN ('member', 'leader')),
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'ended')),
    ended_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (department_id, tenant_membership_id),
    FOREIGN KEY (tenant_id, department_id) REFERENCES system.departments (tenant_id, id),
    FOREIGN KEY (tenant_id, tenant_membership_id) REFERENCES system.tenant_memberships (tenant_id, id),
    CHECK ((status = 'ended') = (ended_at IS NOT NULL))
);

CREATE INDEX idx_department_memberships_tenant_department
    ON system.department_memberships (tenant_id, department_id);
CREATE INDEX idx_department_memberships_tenant_membership
    ON system.department_memberships (tenant_id, tenant_membership_id)
    WHERE status = 'active';
CREATE UNIQUE INDEX uq_department_memberships_active_primary
    ON system.department_memberships (tenant_membership_id)
    WHERE membership_type = 'primary' AND status = 'active';

CREATE TABLE system.project_groups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL REFERENCES system.tenants(id),
    code text NOT NULL CHECK (code = lower(btrim(code)) AND code <> ''),
    name text NOT NULL CHECK (btrim(name) <> ''),
    description text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT 'planned' CHECK (status IN ('planned', 'active', 'closed')),
    starts_at timestamptz,
    ends_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, code),
    UNIQUE (tenant_id, id),
    CHECK (starts_at IS NULL OR ends_at IS NULL OR ends_at > starts_at)
);

CREATE TABLE system.project_group_memberships (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    project_group_id bigint NOT NULL,
    tenant_membership_id bigint NOT NULL,
    relation_role text NOT NULL DEFAULT 'member' CHECK (relation_role IN ('member', 'leader', 'coordinator')),
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'ended')),
    ended_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (project_group_id, tenant_membership_id),
    FOREIGN KEY (tenant_id, project_group_id) REFERENCES system.project_groups (tenant_id, id),
    FOREIGN KEY (tenant_id, tenant_membership_id) REFERENCES system.tenant_memberships (tenant_id, id),
    CHECK ((status = 'ended') = (ended_at IS NOT NULL))
);

CREATE INDEX idx_project_group_memberships_tenant_group
    ON system.project_group_memberships (tenant_id, project_group_id, status);
CREATE INDEX idx_project_group_memberships_tenant_membership
    ON system.project_group_memberships (tenant_id, tenant_membership_id)
    WHERE status = 'active';

CREATE FUNCTION system.validate_user_attribute_authority()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    connection_tenant_id bigint;
BEGIN
    IF NEW.tenant_idp_connection_id IS NULL THEN
        RETURN NEW;
    END IF;

    SELECT tenant_id INTO connection_tenant_id
    FROM system.tenant_idp_connections
    WHERE id = NEW.tenant_idp_connection_id
    FOR KEY SHARE;

    IF NOT EXISTS (
        SELECT 1
        FROM system.tenant_memberships tm
        WHERE tm.tenant_id = connection_tenant_id
          AND tm.principal_id = NEW.user_id
          AND tm.status = 'active'
          AND (tm.expires_at IS NULL OR tm.expires_at > now())
    ) THEN
        RAISE EXCEPTION 'external user attribute authority requires an active membership in the connection tenant'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.validate_department_tree()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.tenant_id <> OLD.tenant_id THEN
        RAISE EXCEPTION 'department tenant cannot change'
            USING ERRCODE = '23514';
    END IF;

    PERFORM 1
    FROM system.tenants
    WHERE id = NEW.tenant_id
    FOR UPDATE;

    IF NEW.parent_id IS NULL THEN
        RETURN NEW;
    END IF;

    IF EXISTS (
        WITH RECURSIVE ancestors(id, parent_id) AS (
            SELECT d.id, d.parent_id
            FROM system.departments d
            WHERE d.tenant_id = NEW.tenant_id AND d.id = NEW.parent_id
            UNION
            SELECT parent.id, parent.parent_id
            FROM system.departments parent
            JOIN ancestors child ON child.parent_id = parent.id
            WHERE parent.tenant_id = NEW.tenant_id
        )
        SELECT 1 FROM ancestors WHERE id = NEW.id
    ) THEN
        RAISE EXCEPTION 'department hierarchy cannot contain a cycle'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.validate_department_membership()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM system.tenant_memberships tm
        JOIN system.principals p ON p.id = tm.principal_id
        JOIN system.departments d
          ON d.tenant_id = NEW.tenant_id AND d.id = NEW.department_id
        WHERE tm.tenant_id = NEW.tenant_id
          AND tm.id = NEW.tenant_membership_id
          AND p.principal_type = 'user'
          AND (NEW.status <> 'active' OR (
              tm.status = 'active'
              AND p.status = 'active'
              AND d.status = 'active'
              AND (tm.expires_at IS NULL OR tm.expires_at > now())
          ))
    ) THEN
        RAISE EXCEPTION 'department membership requires an active user tenant membership'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.prevent_project_group_tenant_change()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.tenant_id <> OLD.tenant_id THEN
        RAISE EXCEPTION 'project group tenant cannot change'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.validate_project_group_membership()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.status = 'active' AND NOT EXISTS (
        SELECT 1
        FROM system.tenant_memberships tm
        JOIN system.principals p ON p.id = tm.principal_id
        JOIN system.project_groups pg
          ON pg.tenant_id = NEW.tenant_id AND pg.id = NEW.project_group_id
        WHERE tm.tenant_id = NEW.tenant_id
          AND tm.id = NEW.tenant_membership_id
          AND tm.status = 'active'
          AND p.status = 'active'
          AND pg.status <> 'closed'
          AND (tm.expires_at IS NULL OR tm.expires_at > now())
    ) THEN
        RAISE EXCEPTION 'active project group membership requires an active principal, tenant membership, and open project group'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

