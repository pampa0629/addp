BEGIN;

CREATE TABLE system.mfa_credentials (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES system.users(id),
    method text NOT NULL CHECK (method = 'totp'),
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    secret_ciphertext bytea NOT NULL CHECK (octet_length(secret_ciphertext) >= 16),
    secret_nonce bytea NOT NULL CHECK (octet_length(secret_nonce) = 12),
    key_version integer NOT NULL DEFAULT 1 CHECK (key_version > 0),
    last_accepted_counter bigint CHECK (last_accepted_counter >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, method)
);

CREATE INDEX idx_mfa_credentials_user_status
    ON system.mfa_credentials (user_id, status);

CREATE TABLE system.mfa_challenges (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash char(64) NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    principal_id bigint NOT NULL REFERENCES system.users(id),
    issued_authorization_version bigint NOT NULL CHECK (issued_authorization_version > 0),
    authentication_methods text[] NOT NULL CHECK (authentication_methods = ARRAY['password']::text[]),
    authenticated_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    failed_attempts integer NOT NULL DEFAULT 0 CHECK (failed_attempts BETWEEN 0 AND 5),
    consumed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (authenticated_at <= created_at),
    CHECK (expires_at > created_at),
    CHECK (consumed_at IS NULL OR consumed_at >= created_at)
);

CREATE INDEX idx_mfa_challenges_principal_created_at
    ON system.mfa_challenges (principal_id, created_at DESC);
CREATE INDEX idx_mfa_challenges_expires_at
    ON system.mfa_challenges (expires_at)
    WHERE consumed_at IS NULL;

CREATE TABLE system.iam_bootstrap_state (
    singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    status text NOT NULL CHECK (status IN ('prepared', 'completed')),
    secret_hash char(64) UNIQUE CHECK (secret_hash IS NULL OR secret_hash ~ '^[0-9a-f]{64}$'),
    prepared_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    completed_at timestamptz,
    CHECK (expires_at > prepared_at),
    CHECK (
        (status = 'prepared' AND secret_hash IS NOT NULL AND completed_at IS NULL)
        OR (status = 'completed' AND secret_hash IS NULL AND completed_at IS NOT NULL
            AND completed_at >= prepared_at)
    )
);

CREATE FUNCTION system.validate_mfa_credential_transition()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.user_id IS DISTINCT FROM OLD.user_id
       OR NEW.method IS DISTINCT FROM OLD.method
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'MFA credential identity is immutable';
    END IF;
    IF NEW.status IS NOT DISTINCT FROM OLD.status
       AND NEW.secret_ciphertext IS NOT DISTINCT FROM OLD.secret_ciphertext
       AND NEW.secret_nonce IS NOT DISTINCT FROM OLD.secret_nonce
       AND NEW.key_version IS NOT DISTINCT FROM OLD.key_version
       AND NEW.last_accepted_counter IS NOT DISTINCT FROM OLD.last_accepted_counter THEN
        RAISE EXCEPTION 'MFA credential update must change a security fact';
    END IF;
    IF OLD.status = 'disabled' AND NEW.status <> 'disabled' THEN
        RAISE EXCEPTION 'disabled MFA credential cannot be reactivated';
    END IF;
    IF NEW.last_accepted_counter IS DISTINCT FROM OLD.last_accepted_counter
       AND OLD.last_accepted_counter IS NOT NULL
       AND (NEW.last_accepted_counter IS NULL
            OR NEW.last_accepted_counter <= OLD.last_accepted_counter) THEN
        RAISE EXCEPTION 'MFA accepted counter must increase';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.validate_mfa_challenge_transition()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.token_hash IS DISTINCT FROM OLD.token_hash
       OR NEW.principal_id IS DISTINCT FROM OLD.principal_id
       OR NEW.issued_authorization_version IS DISTINCT FROM OLD.issued_authorization_version
       OR NEW.authentication_methods IS DISTINCT FROM OLD.authentication_methods
       OR NEW.authenticated_at IS DISTINCT FROM OLD.authenticated_at
       OR NEW.expires_at IS DISTINCT FROM OLD.expires_at
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'MFA challenge identity and authentication binding are immutable';
    END IF;
    IF OLD.consumed_at IS NOT NULL THEN
        RAISE EXCEPTION 'consumed MFA challenge is immutable';
    END IF;
    IF NEW.failed_attempts NOT IN (OLD.failed_attempts, OLD.failed_attempts + 1) THEN
        RAISE EXCEPTION 'MFA challenge failed attempts must increase one at a time';
    END IF;
    IF NEW.failed_attempts = OLD.failed_attempts AND NEW.consumed_at IS NULL THEN
        RAISE EXCEPTION 'MFA challenge update must consume it or record a failed attempt';
    END IF;
    IF NEW.failed_attempts = 5 AND NEW.consumed_at IS NULL THEN
        RAISE EXCEPTION 'MFA challenge must terminate after five failed attempts';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.validate_iam_bootstrap_transition()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.singleton IS DISTINCT FROM OLD.singleton
       OR NEW.prepared_at IS DISTINCT FROM OLD.prepared_at
       OR NEW.expires_at IS DISTINCT FROM OLD.expires_at THEN
        RAISE EXCEPTION 'IAM bootstrap identity and preparation facts are immutable';
    END IF;
    IF OLD.status <> 'prepared'
       OR NEW.status <> 'completed'
       OR NEW.secret_hash IS NOT NULL
       OR NEW.completed_at IS NULL THEN
        RAISE EXCEPTION 'IAM bootstrap may only transition from prepared to completed';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.prevent_iam_security_fact_delete()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'IAM MFA and bootstrap security facts cannot be physically deleted';
END;
$$;

CREATE TRIGGER trg_mfa_credentials_transition
BEFORE UPDATE ON system.mfa_credentials
FOR EACH ROW EXECUTE FUNCTION system.validate_mfa_credential_transition();
CREATE TRIGGER trg_mfa_credentials_updated_at
BEFORE UPDATE ON system.mfa_credentials
FOR EACH ROW EXECUTE FUNCTION system.set_updated_at();
CREATE TRIGGER trg_mfa_credentials_prevent_delete
BEFORE DELETE ON system.mfa_credentials
FOR EACH ROW EXECUTE FUNCTION system.prevent_iam_security_fact_delete();
CREATE TRIGGER trg_mfa_credentials_prevent_truncate
BEFORE TRUNCATE ON system.mfa_credentials
FOR EACH STATEMENT EXECUTE FUNCTION system.prevent_iam_security_fact_delete();

CREATE TRIGGER trg_mfa_challenges_transition
BEFORE UPDATE ON system.mfa_challenges
FOR EACH ROW EXECUTE FUNCTION system.validate_mfa_challenge_transition();
CREATE TRIGGER trg_mfa_challenges_prevent_delete
BEFORE DELETE ON system.mfa_challenges
FOR EACH ROW EXECUTE FUNCTION system.prevent_iam_security_fact_delete();
CREATE TRIGGER trg_mfa_challenges_prevent_truncate
BEFORE TRUNCATE ON system.mfa_challenges
FOR EACH STATEMENT EXECUTE FUNCTION system.prevent_iam_security_fact_delete();

CREATE TRIGGER trg_iam_bootstrap_state_transition
BEFORE UPDATE ON system.iam_bootstrap_state
FOR EACH ROW EXECUTE FUNCTION system.validate_iam_bootstrap_transition();
CREATE TRIGGER trg_iam_bootstrap_state_prevent_delete
BEFORE DELETE ON system.iam_bootstrap_state
FOR EACH ROW EXECUTE FUNCTION system.prevent_iam_security_fact_delete();
CREATE TRIGGER trg_iam_bootstrap_state_prevent_truncate
BEFORE TRUNCATE ON system.iam_bootstrap_state
FOR EACH STATEMENT EXECUTE FUNCTION system.prevent_iam_security_fact_delete();

REVOKE DELETE, TRUNCATE ON system.mfa_credentials FROM PUBLIC;
REVOKE DELETE, TRUNCATE ON system.mfa_challenges FROM PUBLIC;
REVOKE DELETE, TRUNCATE ON system.iam_bootstrap_state FROM PUBLIC;

COMMIT;
