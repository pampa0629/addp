BEGIN;

CREATE TABLE system.module_definitions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_name varchar(50) NOT NULL UNIQUE,
    route_prefix varchar(50) NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    configuration_management jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_module_definitions_enabled ON system.module_definitions (enabled);

CREATE TABLE system.module_runtime_instances (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_definition_id bigint NOT NULL REFERENCES system.module_definitions(id) ON DELETE RESTRICT,
    instance_id varchar(100) NOT NULL,
    role varchar(30) NOT NULL,
    module_url varchar(255),
    health_check_url varchar(255),
    status varchar(20) NOT NULL DEFAULT 'up' CHECK (status IN ('up', 'down')),
    last_heartbeat timestamptz NOT NULL,
    lease_expires_at timestamptz NOT NULL,
    metadata jsonb,
    registered_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (module_definition_id, instance_id),
    CHECK (role <> ''),
    CHECK (role <> 'backend' OR nullif(btrim(module_url), '') IS NOT NULL)
);

CREATE INDEX idx_module_runtime_instances_role ON system.module_runtime_instances (role);
CREATE INDEX idx_module_runtime_instances_status ON system.module_runtime_instances (status);
CREATE INDEX idx_module_runtime_instances_lease ON system.module_runtime_instances (lease_expires_at);

-- 旧表中只有定义与单实例混合快照。升级时只迁移持久定义；运行实例必须由
-- 当前进程使用新的 instance_id 重新注册，不能把旧快照伪装成有效租约。
DO $$
BEGIN
    IF to_regclass('system.module_registry') IS NOT NULL THEN
        INSERT INTO system.module_definitions (
            module_name, route_prefix, enabled, configuration_management, created_at, updated_at
        )
        SELECT module_name,
               route_prefix,
               true,
               configuration_management,
               coalesce(created_at, now()),
               coalesce(updated_at, now())
        FROM system.module_registry
        ON CONFLICT (module_name) DO NOTHING;

        DROP TABLE system.module_registry;
    END IF;
END $$;

COMMIT;
