BEGIN;

CREATE FUNCTION system.valid_scope_types(values_to_check text[])
RETURNS boolean
LANGUAGE sql
IMMUTABLE
AS $$
    SELECT cardinality(values_to_check) > 0
       AND values_to_check <@ ARRAY['platform', 'tenant', 'department', 'project_group']::text[]
       AND cardinality(values_to_check) = (
           SELECT count(DISTINCT value)::integer FROM unnest(values_to_check) AS value
       );
$$;

CREATE FUNCTION system.valid_principal_types(values_to_check text[])
RETURNS boolean
LANGUAGE sql
IMMUTABLE
AS $$
    SELECT cardinality(values_to_check) > 0
       AND values_to_check <@ ARRAY['user', 'service_principal']::text[]
       AND cardinality(values_to_check) = (
           SELECT count(DISTINCT value)::integer FROM unnest(values_to_check) AS value
       );
$$;

CREATE TABLE system.permissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_key text NOT NULL UNIQUE CHECK (permission_key ~ '^[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*$'),
    owner_module text NOT NULL CHECK (owner_module ~ '^[a-z][a-z0-9_]*$'),
    action text NOT NULL CHECK (action ~ '^[a-z][a-z0-9_]*$'),
    risk_level text NOT NULL CHECK (risk_level IN ('low', 'medium', 'high', 'critical')),
    delegable boolean NOT NULL DEFAULT false,
    allowed_scope_types text[] NOT NULL CHECK (system.valid_scope_types(allowed_scope_types)),
    tenant_customizable boolean NOT NULL DEFAULT false,
    name_i18n_key text NOT NULL CHECK (btrim(name_i18n_key) <> ''),
    description_i18n_key text NOT NULL CHECK (btrim(description_i18n_key) <> ''),
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (split_part(permission_key, '.', 3) = action)
);

CREATE TABLE system.roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint REFERENCES system.tenants(id),
    role_key text NOT NULL CHECK (role_key ~ '^[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*$'),
    name text,
    description text,
    name_i18n_key text,
    description_i18n_key text,
    role_type text NOT NULL CHECK (role_type IN ('platform_builtin', 'tenant_builtin', 'tenant_custom')),
    allowed_scope_types text[] NOT NULL CHECK (system.valid_scope_types(allowed_scope_types)),
    allowed_principal_types text[] NOT NULL CHECK (system.valid_principal_types(allowed_principal_types)),
    immutable boolean NOT NULL,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    created_by_principal_id bigint REFERENCES system.principals(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE NULLS NOT DISTINCT (tenant_id, role_key),
    CHECK (
        (role_type IN ('platform_builtin', 'tenant_builtin')
            AND tenant_id IS NULL
            AND name IS NULL
            AND description IS NULL
            AND name_i18n_key IS NOT NULL
            AND description_i18n_key IS NOT NULL
            AND btrim(name_i18n_key) <> ''
            AND btrim(description_i18n_key) <> ''
            AND immutable
            AND created_by_principal_id IS NULL)
        OR (role_type = 'tenant_custom'
            AND tenant_id IS NOT NULL
            AND name IS NOT NULL
            AND btrim(name) <> ''
            AND name_i18n_key IS NULL
            AND description_i18n_key IS NULL
            AND NOT immutable
            AND created_by_principal_id IS NOT NULL)
    ),
    CHECK (
        (role_type = 'platform_builtin'
            AND allowed_scope_types = ARRAY['platform']::text[])
        OR (role_type IN ('tenant_builtin', 'tenant_custom')
            AND NOT ('platform' = ANY(allowed_scope_types)))
    )
);

