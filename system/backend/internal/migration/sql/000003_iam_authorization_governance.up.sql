CREATE FUNCTION system.validate_privileged_change_approval()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    target_request system.privileged_change_requests%ROWTYPE;
    reviewer_type text;
    reviewer_status text;
BEGIN
    SELECT principal_type, status INTO reviewer_type, reviewer_status
    FROM system.principals
    WHERE id = NEW.reviewer_principal_id
    FOR KEY SHARE;

    SELECT * INTO target_request
    FROM system.privileged_change_requests
    WHERE id = NEW.request_id
    FOR UPDATE;

    IF target_request.status <> 'pending' THEN
        RAISE EXCEPTION 'privileged change request is not pending'
            USING ERRCODE = '23514';
    END IF;
    IF reviewer_type <> 'user'
       OR reviewer_status <> 'active'
       OR NEW.reviewer_principal_id = target_request.requested_by_principal_id
       OR NEW.reviewer_principal_id = target_request.target_principal_id THEN
        RAISE EXCEPTION 'privileged change reviewer must be a distinct user'
            USING ERRCODE = '23514';
    END IF;
    IF NEW.decided_at < target_request.requested_at THEN
        RAISE EXCEPTION 'privileged change decision cannot precede the request'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.complete_privileged_change_approval()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE system.privileged_change_requests
    SET status = NEW.decision,
        decided_at = NEW.decided_at,
        updated_at = now()
    WHERE id = NEW.request_id;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.validate_role_assignment()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    target_principal system.principals%ROWTYPE;
    target_role system.roles%ROWTYPE;
    target_request system.privileged_change_requests%ROWTYPE;
BEGIN
    SELECT * INTO target_principal
    FROM system.principals
    WHERE id = NEW.principal_id
    FOR UPDATE;
    SELECT * INTO target_role
    FROM system.roles
    WHERE id = NEW.role_id
    FOR KEY SHARE;

    IF TG_OP = 'UPDATE' THEN
        IF OLD.status = 'revoked' THEN
            RAISE EXCEPTION 'revoked role assignment is immutable'
                USING ERRCODE = '23514';
        END IF;
        IF NEW.principal_id <> OLD.principal_id
           OR NEW.role_id <> OLD.role_id
           OR NEW.scope_type <> OLD.scope_type
           OR NEW.tenant_id IS DISTINCT FROM OLD.tenant_id
           OR NEW.department_id IS DISTINCT FROM OLD.department_id
           OR NEW.project_group_id IS DISTINCT FROM OLD.project_group_id
           OR NEW.source_type <> OLD.source_type
           OR NEW.created_by_principal_id IS DISTINCT FROM OLD.created_by_principal_id
           OR NEW.grant_change_request_id IS DISTINCT FROM OLD.grant_change_request_id
           OR NEW.valid_from <> OLD.valid_from
           OR NEW.valid_until IS DISTINCT FROM OLD.valid_until
           OR NEW.reason <> OLD.reason
           OR NEW.created_at <> OLD.created_at THEN
            RAISE EXCEPTION 'role assignment identity cannot change'
                USING ERRCODE = '23514';
        END IF;
        IF OLD.status = 'active' AND NEW.status <> 'revoked' THEN
            RAISE EXCEPTION 'role assignment status may only move from active to revoked'
                USING ERRCODE = '23514';
        END IF;
    ELSIF NEW.status <> 'active' THEN
        RAISE EXCEPTION 'new role assignment must be active'
            USING ERRCODE = '23514';
    END IF;

    IF NEW.status = 'active' THEN
        IF target_principal.status <> 'active' OR target_role.status <> 'active' THEN
            RAISE EXCEPTION 'active role assignment requires an active principal and role'
                USING ERRCODE = '23514';
        END IF;
        IF NOT (target_principal.principal_type = ANY(target_role.allowed_principal_types))
           OR NOT (NEW.scope_type = ANY(target_role.allowed_scope_types)) THEN
            RAISE EXCEPTION 'role assignment principal type or scope is not allowed by the role'
                USING ERRCODE = '23514';
        END IF;
        IF NEW.scope_type = 'platform' AND target_role.role_type <> 'platform_builtin' THEN
            RAISE EXCEPTION 'platform scope requires a platform built-in role'
                USING ERRCODE = '23514';
        END IF;
        IF NEW.scope_type <> 'platform' AND target_role.role_type = 'platform_builtin' THEN
            RAISE EXCEPTION 'platform built-in role only supports platform scope'
                USING ERRCODE = '23514';
        END IF;
        IF target_role.role_type = 'tenant_custom' AND target_role.tenant_id <> NEW.tenant_id THEN
            RAISE EXCEPTION 'tenant custom role may only be assigned in its own tenant'
                USING ERRCODE = '23514';
        END IF;

        IF NEW.scope_type <> 'platform' AND NOT EXISTS (
            SELECT 1
            FROM system.tenant_memberships tm
            WHERE tm.tenant_id = NEW.tenant_id
              AND tm.principal_id = NEW.principal_id
              AND tm.status = 'active'
              AND (tm.expires_at IS NULL OR tm.expires_at > now())
        ) THEN
            RAISE EXCEPTION 'non-platform role assignment requires an active tenant membership'
                USING ERRCODE = '23514';
        END IF;
        IF NEW.scope_type = 'department' AND NOT EXISTS (
            SELECT 1
            FROM system.department_memberships dm
            JOIN system.tenant_memberships tm ON tm.id = dm.tenant_membership_id
            JOIN system.departments d ON d.id = dm.department_id
            WHERE dm.tenant_id = NEW.tenant_id
              AND dm.department_id = NEW.department_id
              AND tm.principal_id = NEW.principal_id
              AND dm.status = 'active'
              AND d.status = 'active'
        ) THEN
            RAISE EXCEPTION 'department role assignment requires an active department membership'
                USING ERRCODE = '23514';
        END IF;
        IF NEW.scope_type = 'project_group' AND NOT EXISTS (
            SELECT 1
            FROM system.project_group_memberships pgm
            JOIN system.tenant_memberships tm ON tm.id = pgm.tenant_membership_id
            JOIN system.project_groups pg ON pg.id = pgm.project_group_id
            WHERE pgm.tenant_id = NEW.tenant_id
              AND pgm.project_group_id = NEW.project_group_id
              AND tm.principal_id = NEW.principal_id
              AND pgm.status = 'active'
              AND pg.status <> 'closed'
        ) THEN
            RAISE EXCEPTION 'project group role assignment requires an active project group membership'
                USING ERRCODE = '23514';
        END IF;

        IF TG_OP = 'INSERT' AND EXISTS (
            SELECT 1
            FROM system.role_assignments existing
            JOIN system.role_conflicts conflict
              ON (conflict.role_id_low = LEAST(existing.role_id, NEW.role_id)
                  AND conflict.role_id_high = GREATEST(existing.role_id, NEW.role_id))
            WHERE existing.principal_id = NEW.principal_id
              AND existing.status = 'active'
              AND (existing.valid_until IS NULL OR existing.valid_until > now())
        ) THEN
            RAISE EXCEPTION 'principal already has a conflicting active role'
                USING ERRCODE = '23514';
        END IF;

        IF NEW.scope_type = 'platform' AND NEW.source_type <> 'bootstrap' THEN
            IF NEW.grant_change_request_id IS NULL THEN
                RAISE EXCEPTION 'platform role assignment requires an approved grant request'
                    USING ERRCODE = '23514';
            END IF;
            SELECT * INTO target_request
            FROM system.privileged_change_requests
            WHERE id = NEW.grant_change_request_id
            FOR UPDATE;
            IF target_request.status <> 'approved'
               OR target_request.change_type <> 'platform_role_grant'
               OR target_request.target_principal_id <> NEW.principal_id
               OR target_request.target_role_id <> NEW.role_id
               OR target_request.requested_by_principal_id <> NEW.created_by_principal_id THEN
                RAISE EXCEPTION 'platform role grant request does not match the assignment'
                    USING ERRCODE = '23514';
            END IF;
        ELSIF NEW.grant_change_request_id IS NOT NULL THEN
            RAISE EXCEPTION 'grant request is only valid for non-bootstrap platform assignments'
                USING ERRCODE = '23514';
        END IF;
    END IF;

    IF NEW.status = 'revoked' THEN
        IF NEW.scope_type = 'platform' THEN
            IF NEW.revoke_change_request_id IS NULL THEN
                RAISE EXCEPTION 'platform role revocation requires an approved revoke request'
                    USING ERRCODE = '23514';
            END IF;
            SELECT * INTO target_request
            FROM system.privileged_change_requests
            WHERE id = NEW.revoke_change_request_id
            FOR UPDATE;
            IF target_request.status <> 'approved'
               OR target_request.change_type <> 'platform_role_revoke'
               OR target_request.target_principal_id <> NEW.principal_id
               OR target_request.target_role_id <> NEW.role_id
               OR target_request.requested_by_principal_id <> NEW.revoked_by_principal_id THEN
                RAISE EXCEPTION 'platform role revoke request does not match the assignment'
                    USING ERRCODE = '23514';
            END IF;
        ELSIF NEW.revoke_change_request_id IS NOT NULL THEN
            RAISE EXCEPTION 'revoke request is only valid for platform assignments'
                USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.apply_role_assignment_privileged_request()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    request_to_apply bigint;
BEGIN
    IF TG_OP = 'INSERT' THEN
        request_to_apply := NEW.grant_change_request_id;
    ELSIF NEW.status = 'revoked' AND OLD.status = 'active' THEN
        request_to_apply := NEW.revoke_change_request_id;
    END IF;

    IF request_to_apply IS NOT NULL THEN
        UPDATE system.privileged_change_requests
        SET status = 'applied',
            applied_at = now(),
            updated_at = now()
        WHERE id = request_to_apply;
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.bump_assignment_authorization_version()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    affected_principal_id bigint;
BEGIN
    IF TG_OP = 'DELETE' THEN
        affected_principal_id := OLD.principal_id;
    ELSE
        affected_principal_id := NEW.principal_id;
    END IF;
    UPDATE system.principals
    SET authorization_version = authorization_version + 1,
        updated_at = now()
    WHERE id = affected_principal_id;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.bump_role_holders_authorization_version()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    affected_role_id bigint;
BEGIN
    IF TG_TABLE_NAME = 'role_permissions' THEN
        IF TG_OP = 'DELETE' THEN
            affected_role_id := OLD.role_id;
        ELSE
            affected_role_id := NEW.role_id;
        END IF;
        PERFORM 1
        FROM system.principals p
        WHERE EXISTS (
            SELECT 1 FROM system.role_assignments assignment
            WHERE assignment.role_id = affected_role_id
              AND assignment.principal_id = p.id
              AND assignment.status = 'active'
        )
        ORDER BY p.id
        FOR UPDATE;

        UPDATE system.principals p
        SET authorization_version = p.authorization_version + 1,
            updated_at = now()
        WHERE EXISTS (
            SELECT 1 FROM system.role_assignments assignment
            WHERE assignment.role_id = affected_role_id
              AND assignment.principal_id = p.id
              AND assignment.status = 'active'
        );
    ELSIF TG_TABLE_NAME = 'roles' THEN
        PERFORM 1
        FROM system.principals p
        WHERE EXISTS (
            SELECT 1 FROM system.role_assignments assignment
            WHERE assignment.role_id = NEW.id
              AND assignment.principal_id = p.id
              AND assignment.status = 'active'
        )
        ORDER BY p.id
        FOR UPDATE;

        UPDATE system.principals p
        SET authorization_version = p.authorization_version + 1,
            updated_at = now()
        WHERE EXISTS (
            SELECT 1 FROM system.role_assignments assignment
            WHERE assignment.role_id = NEW.id
              AND assignment.principal_id = p.id
              AND assignment.status = 'active'
        );
    ELSE
        PERFORM 1
        FROM system.principals p
        WHERE EXISTS (
            SELECT 1
            FROM system.role_assignments assignment
            JOIN system.role_permissions rp ON rp.role_id = assignment.role_id
            WHERE rp.permission_id = NEW.id
              AND assignment.principal_id = p.id
              AND assignment.status = 'active'
        )
        ORDER BY p.id
        FOR UPDATE;

        UPDATE system.principals p
        SET authorization_version = p.authorization_version + 1,
            updated_at = now()
        WHERE EXISTS (
            SELECT 1
            FROM system.role_assignments assignment
            JOIN system.role_permissions rp ON rp.role_id = assignment.role_id
            WHERE rp.permission_id = NEW.id
              AND assignment.principal_id = p.id
              AND assignment.status = 'active'
        );
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.validate_principal_privileged_status_change()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    expected_change_type text;
    target_request system.privileged_change_requests%ROWTYPE;
    requires_approval boolean;
BEGIN
    IF NEW.status = OLD.status THEN
        IF NEW.status_change_request_id IS DISTINCT FROM OLD.status_change_request_id THEN
            RAISE EXCEPTION 'principal status request may only change with principal status'
                USING ERRCODE = '23514';
        END IF;
        RETURN NEW;
    END IF;

    NEW.authorization_version := OLD.authorization_version + 1;
    SELECT EXISTS (
        SELECT 1
        FROM system.role_assignments assignment
        WHERE assignment.principal_id = OLD.id
          AND assignment.scope_type = 'platform'
          AND assignment.status = 'active'
          AND assignment.valid_from <= now()
          AND (assignment.valid_until IS NULL OR assignment.valid_until > now())
    ) INTO requires_approval;

    IF NEW.principal_type = 'user'
       AND requires_approval
       AND NEW.status IN ('suspended', 'deactivated') THEN
        expected_change_type := CASE NEW.status
            WHEN 'suspended' THEN 'platform_identity_suspend'
            ELSE 'platform_identity_deactivate'
        END;
        IF NEW.status_change_request_id IS NULL
           OR NEW.status_change_request_id IS NOT DISTINCT FROM OLD.status_change_request_id THEN
            RAISE EXCEPTION 'governed principal status change requires a new approved request'
                USING ERRCODE = '23514';
        END IF;
        SELECT * INTO target_request
        FROM system.privileged_change_requests
        WHERE id = NEW.status_change_request_id
        FOR UPDATE;
        IF target_request.status <> 'approved'
           OR target_request.change_type <> expected_change_type
           OR target_request.target_principal_id <> NEW.id THEN
            RAISE EXCEPTION 'identity change request does not match the principal status change'
                USING ERRCODE = '23514';
        END IF;
    ELSIF NEW.status_change_request_id IS DISTINCT FROM OLD.status_change_request_id THEN
        RAISE EXCEPTION 'status change request is only valid for governed user suspension or deactivation'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.apply_principal_status_change_request()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.status <> OLD.status
       AND NEW.status_change_request_id IS DISTINCT FROM OLD.status_change_request_id
       AND NEW.status_change_request_id IS NOT NULL THEN
        UPDATE system.privileged_change_requests
        SET status = 'applied',
            applied_at = now(),
            updated_at = now()
        WHERE id = NEW.status_change_request_id;
    END IF;
    RETURN NEW;
END;
$$;

