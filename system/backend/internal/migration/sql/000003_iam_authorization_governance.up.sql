CREATE FUNCTION system.validate_permission_update()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.permission_key <> OLD.permission_key
       OR NEW.owner_module <> OLD.owner_module
       OR NEW.action <> OLD.action
       OR NEW.created_at <> OLD.created_at THEN
        RAISE EXCEPTION 'permission key, owner, and action cannot change'
            USING ERRCODE = '23514';
    END IF;
    IF EXISTS (
        SELECT 1
        FROM system.role_permissions rp
        JOIN system.roles role ON role.id = rp.role_id
        WHERE rp.permission_id = OLD.id
          AND NOT (role.allowed_scope_types <@ NEW.allowed_scope_types)
    ) THEN
        RAISE EXCEPTION 'permission scope cannot exclude an existing role scope'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.validate_role()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND (
        NEW.tenant_id IS DISTINCT FROM OLD.tenant_id
        OR NEW.role_key <> OLD.role_key
        OR NEW.role_type <> OLD.role_type
        OR NEW.created_by_principal_id IS DISTINCT FROM OLD.created_by_principal_id
        OR NEW.created_at <> OLD.created_at
    ) THEN
        RAISE EXCEPTION 'role identity cannot change'
            USING ERRCODE = '23514';
    END IF;

    IF TG_OP = 'INSERT' AND NEW.role_type = 'tenant_custom' AND NOT EXISTS (
        SELECT 1
        FROM system.tenant_memberships tm
        JOIN system.principals p ON p.id = tm.principal_id
        WHERE tm.tenant_id = NEW.tenant_id
          AND tm.principal_id = NEW.created_by_principal_id
          AND tm.status = 'active'
          AND p.status = 'active'
          AND (tm.expires_at IS NULL OR tm.expires_at > now())
    ) THEN
        RAISE EXCEPTION 'tenant custom role creator must have an active membership in the same tenant'
            USING ERRCODE = '23514';
    END IF;

    IF TG_OP = 'UPDATE' AND EXISTS (
        SELECT 1
        FROM system.role_permissions rp
        JOIN system.permissions permission ON permission.id = rp.permission_id
        WHERE rp.role_id = OLD.id
          AND NOT (NEW.allowed_scope_types <@ permission.allowed_scope_types)
    ) THEN
        RAISE EXCEPTION 'role scope exceeds an existing permission scope'
            USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'UPDATE' AND EXISTS (
        SELECT 1
        FROM system.role_assignments assignment
        JOIN system.principals principal ON principal.id = assignment.principal_id
        WHERE assignment.role_id = OLD.id
          AND assignment.status = 'active'
          AND (
              NOT (assignment.scope_type = ANY(NEW.allowed_scope_types))
              OR NOT (principal.principal_type = ANY(NEW.allowed_principal_types))
          )
    ) THEN
        RAISE EXCEPTION 'role scope or principal type cannot exclude an active assignment'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.validate_role_permission()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    target_role system.roles%ROWTYPE;
    target_permission system.permissions%ROWTYPE;
BEGIN
    IF TG_OP = 'UPDATE' AND (
        NEW.role_id <> OLD.role_id
        OR NEW.permission_id <> OLD.permission_id
        OR NEW.source_type <> OLD.source_type
        OR NEW.created_by_principal_id IS DISTINCT FROM OLD.created_by_principal_id
        OR NEW.created_at <> OLD.created_at
    ) THEN
        RAISE EXCEPTION 'role permission identity cannot change'
            USING ERRCODE = '23514';
    END IF;

    SELECT * INTO target_role FROM system.roles WHERE id = NEW.role_id FOR KEY SHARE;
    SELECT * INTO target_permission FROM system.permissions WHERE id = NEW.permission_id FOR KEY SHARE;

    IF target_role.status <> 'active' OR target_permission.status <> 'active' THEN
        RAISE EXCEPTION 'role permission requires an active role and permission'
            USING ERRCODE = '23514';
    END IF;
    IF NOT (target_role.allowed_scope_types <@ target_permission.allowed_scope_types) THEN
        RAISE EXCEPTION 'role scope exceeds permission scope'
            USING ERRCODE = '23514';
    END IF;
    IF NEW.source_type = 'product' AND target_role.role_type = 'tenant_custom' THEN
        RAISE EXCEPTION 'product role permission requires a built-in role'
            USING ERRCODE = '23514';
    END IF;
    IF NEW.source_type = 'tenant' AND (
        target_role.role_type <> 'tenant_custom' OR NOT target_permission.tenant_customizable
    ) THEN
        RAISE EXCEPTION 'tenant role permission requires a customizable permission and tenant custom role'
            USING ERRCODE = '23514';
    END IF;
    IF NEW.source_type = 'tenant' AND NOT EXISTS (
        SELECT 1
        FROM system.tenant_memberships tm
        JOIN system.principals p ON p.id = tm.principal_id
        WHERE tm.tenant_id = target_role.tenant_id
          AND tm.principal_id = NEW.created_by_principal_id
          AND tm.status = 'active'
          AND p.status = 'active'
          AND (tm.expires_at IS NULL OR tm.expires_at > now())
    ) THEN
        RAISE EXCEPTION 'tenant role permission creator must have an active membership in the role tenant'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.validate_privileged_change_request()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    target_type text;
    requester_type text;
    target_status text;
    requester_status text;
    target_role system.roles%ROWTYPE;
BEGIN
    PERFORM 1
    FROM system.principals
    WHERE id IN (NEW.target_principal_id, NEW.requested_by_principal_id)
    ORDER BY id
    FOR KEY SHARE;

    SELECT principal_type, status INTO target_type, target_status
    FROM system.principals
    WHERE id = NEW.target_principal_id;
    SELECT principal_type, status INTO requester_type, requester_status
    FROM system.principals
    WHERE id = NEW.requested_by_principal_id;

    IF NEW.status <> 'pending' OR NEW.decided_at IS NOT NULL OR NEW.applied_at IS NOT NULL THEN
        RAISE EXCEPTION 'new privileged change request must be pending'
            USING ERRCODE = '23514';
    END IF;
    IF target_type <> 'user' OR requester_type <> 'user' OR requester_status <> 'active' THEN
        RAISE EXCEPTION 'privileged change target and requester must be users'
            USING ERRCODE = '23514';
    END IF;

    IF NEW.target_role_id IS NOT NULL THEN
        SELECT * INTO target_role FROM system.roles WHERE id = NEW.target_role_id FOR KEY SHARE;
        IF target_role.role_type <> 'platform_builtin'
           OR target_role.status <> 'active'
           OR target_role.allowed_scope_types <> ARRAY['platform']::text[] THEN
            RAISE EXCEPTION 'platform role change requires an active platform built-in role'
                USING ERRCODE = '23514';
        END IF;
    END IF;

    IF NEW.change_type = 'platform_role_grant' AND (
        target_status <> 'active' OR EXISTS (
            SELECT 1
            FROM system.role_assignments assignment
            WHERE assignment.principal_id = NEW.target_principal_id
              AND assignment.role_id = NEW.target_role_id
              AND assignment.scope_type = 'platform'
              AND assignment.status = 'active'
        )
    ) THEN
        RAISE EXCEPTION 'platform role grant requires an active target without the role'
            USING ERRCODE = '23514';
    END IF;
    IF NEW.change_type = 'platform_role_revoke' AND NOT EXISTS (
        SELECT 1
        FROM system.role_assignments assignment
        WHERE assignment.principal_id = NEW.target_principal_id
          AND assignment.role_id = NEW.target_role_id
          AND assignment.scope_type = 'platform'
          AND assignment.status = 'active'
          AND assignment.valid_from <= now()
          AND (assignment.valid_until IS NULL OR assignment.valid_until > now())
    ) THEN
        RAISE EXCEPTION 'platform role revoke requires an effective target assignment'
            USING ERRCODE = '23514';
    END IF;
    IF NEW.change_type = 'platform_identity_suspend' AND target_status <> 'active' THEN
        RAISE EXCEPTION 'platform identity suspend requires an active target'
            USING ERRCODE = '23514';
    END IF;
    IF NEW.change_type = 'platform_identity_deactivate' AND target_status = 'deactivated' THEN
        RAISE EXCEPTION 'platform identity deactivate requires a non-deactivated target'
            USING ERRCODE = '23514';
    END IF;
    IF NEW.change_type IN ('platform_identity_suspend', 'platform_identity_deactivate') AND NOT EXISTS (
        SELECT 1
        FROM system.role_assignments assignment
        WHERE assignment.principal_id = NEW.target_principal_id
          AND assignment.scope_type = 'platform'
          AND assignment.status = 'active'
          AND assignment.valid_from <= now()
          AND (assignment.valid_until IS NULL OR assignment.valid_until > now())
    ) THEN
        RAISE EXCEPTION 'platform identity change requires an effective platform role assignment'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.validate_privileged_change_request_transition()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.change_type <> OLD.change_type
       OR NEW.target_principal_id <> OLD.target_principal_id
       OR NEW.target_role_id IS DISTINCT FROM OLD.target_role_id
       OR NEW.scope_type <> OLD.scope_type
       OR NEW.reason <> OLD.reason
       OR NEW.requested_by_principal_id <> OLD.requested_by_principal_id
       OR NEW.requested_at <> OLD.requested_at
       OR NEW.created_at <> OLD.created_at THEN
        RAISE EXCEPTION 'privileged change request identity cannot change'
            USING ERRCODE = '23514';
    END IF;

    IF NEW.status = OLD.status THEN
        IF NEW.decided_at IS DISTINCT FROM OLD.decided_at
           OR NEW.applied_at IS DISTINCT FROM OLD.applied_at THEN
            RAISE EXCEPTION 'privileged change decision timestamps cannot change without a status transition'
                USING ERRCODE = '23514';
        END IF;
        RETURN NEW;
    END IF;
    IF OLD.status = 'pending' AND NEW.status = 'cancelled' THEN
        RETURN NEW;
    END IF;
    IF OLD.status = 'pending' AND NEW.status IN ('approved', 'rejected') AND EXISTS (
        SELECT 1
        FROM system.privileged_change_approvals approval
        WHERE approval.request_id = OLD.id
          AND approval.decision = NEW.status
    ) THEN
        RETURN NEW;
    END IF;
    IF OLD.status = 'approved' AND NEW.status = 'applied' AND (
        (OLD.change_type = 'platform_role_grant' AND EXISTS (
            SELECT 1 FROM system.role_assignments assignment
            WHERE assignment.grant_change_request_id = OLD.id
        ))
        OR (OLD.change_type = 'platform_role_revoke' AND EXISTS (
            SELECT 1 FROM system.role_assignments assignment
            WHERE assignment.revoke_change_request_id = OLD.id AND assignment.status = 'revoked'
        ))
        OR (OLD.change_type = 'platform_identity_suspend' AND EXISTS (
            SELECT 1 FROM system.principals principal
            WHERE principal.id = OLD.target_principal_id
              AND principal.status = 'suspended'
              AND principal.status_change_request_id = OLD.id
        ))
        OR (OLD.change_type = 'platform_identity_deactivate' AND EXISTS (
            SELECT 1 FROM system.principals principal
            WHERE principal.id = OLD.target_principal_id
              AND principal.status = 'deactivated'
              AND principal.status_change_request_id = OLD.id
        ))
    ) THEN
        RETURN NEW;
    END IF;

    RAISE EXCEPTION 'invalid privileged change request status transition from % to %', OLD.status, NEW.status
        USING ERRCODE = '23514';
END;
$$;

