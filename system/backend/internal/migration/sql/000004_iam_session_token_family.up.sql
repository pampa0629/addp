CREATE FUNCTION system.validate_refresh_token()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    target_family system.refresh_token_families%ROWTYPE;
    target_access system.access_tokens%ROWTYPE;
    parent_token system.refresh_tokens%ROWTYPE;
BEGIN
    SELECT * INTO target_family
    FROM system.refresh_token_families
    WHERE id = NEW.family_id
    FOR KEY SHARE;
    SELECT * INTO target_access
    FROM system.access_tokens
    WHERE id = NEW.issued_access_token_id
    FOR KEY SHARE;

    IF NEW.used_at IS NOT NULL OR NEW.reuse_detected_at IS NOT NULL OR NEW.revoked_at IS NOT NULL OR NEW.replaced_by_token_id IS NOT NULL THEN
        RAISE EXCEPTION 'new refresh token must be current and unused'
            USING ERRCODE = '23514';
    END IF;
    IF target_family.revoked_at IS NOT NULL
       OR target_family.expires_at <= now()
       OR target_access.family_id <> NEW.family_id
       OR target_access.revoked_at IS NOT NULL
       OR NEW.expires_at > target_family.expires_at THEN
        RAISE EXCEPTION 'refresh token requires an active family and matching access token'
            USING ERRCODE = '23514';
    END IF;
    IF NEW.parent_token_id IS NOT NULL THEN
        SELECT * INTO parent_token
        FROM system.refresh_tokens
        WHERE id = NEW.parent_token_id
        FOR UPDATE;
        IF parent_token.family_id <> NEW.family_id
           OR parent_token.used_at IS NULL
           OR parent_token.replaced_by_token_id IS NOT NULL THEN
            RAISE EXCEPTION 'refresh token parent must be a used unreplaced token in the same family'
                USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.validate_refresh_token_update()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    replacement system.refresh_tokens%ROWTYPE;
BEGIN
    IF NEW.token_hash <> OLD.token_hash
       OR NEW.family_id <> OLD.family_id
       OR NEW.issued_access_token_id <> OLD.issued_access_token_id
       OR NEW.parent_token_id IS DISTINCT FROM OLD.parent_token_id
       OR NEW.expires_at <> OLD.expires_at
       OR NEW.created_at <> OLD.created_at
       OR (OLD.used_at IS NOT NULL AND NEW.used_at IS DISTINCT FROM OLD.used_at)
       OR (OLD.reuse_detected_at IS NOT NULL AND NEW.reuse_detected_at IS DISTINCT FROM OLD.reuse_detected_at)
       OR (OLD.revoked_at IS NOT NULL AND NEW.revoked_at IS DISTINCT FROM OLD.revoked_at)
       OR (OLD.replaced_by_token_id IS NOT NULL AND NEW.replaced_by_token_id IS DISTINCT FROM OLD.replaced_by_token_id) THEN
        RAISE EXCEPTION 'refresh token identity and terminal facts are immutable'
            USING ERRCODE = '23514';
    END IF;
    IF NEW.replaced_by_token_id IS NOT NULL AND OLD.replaced_by_token_id IS NULL THEN
        SELECT * INTO replacement
        FROM system.refresh_tokens
        WHERE id = NEW.replaced_by_token_id
        FOR KEY SHARE;
        IF replacement.family_id <> NEW.family_id OR replacement.parent_token_id <> NEW.id THEN
            RAISE EXCEPTION 'refresh token replacement must be the matching child in the same family'
                USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

