CREATE FUNCTION system.validate_context_selection_option()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    target_ticket system.context_selection_tickets%ROWTYPE;
BEGIN
    SELECT * INTO target_ticket
    FROM system.context_selection_tickets
    WHERE id = NEW.ticket_id
    FOR UPDATE;

    IF target_ticket.consumed_at IS NOT NULL OR target_ticket.expires_at <= now() THEN
        RAISE EXCEPTION 'context selection ticket is not pending'
            USING ERRCODE = '23514';
    END IF;
    IF NEW.context_type = 'platform' AND (
        target_ticket.assurance_level NOT IN ('aal2', 'aal3') OR NOT EXISTS (
            SELECT 1
            FROM system.role_assignments assignment
            WHERE assignment.principal_id = target_ticket.principal_id
              AND assignment.scope_type = 'platform'
              AND assignment.status = 'active'
              AND assignment.valid_from <= now()
              AND (assignment.valid_until IS NULL OR assignment.valid_until > now())
        )
    ) THEN
        RAISE EXCEPTION 'platform context option requires aal2 and an effective platform role'
            USING ERRCODE = '23514';
    END IF;
    IF NEW.context_type = 'tenant' AND NOT EXISTS (
        SELECT 1
        FROM system.tenant_memberships membership
        JOIN system.tenants tenant ON tenant.id = membership.tenant_id
        WHERE membership.id = NEW.tenant_membership_id
          AND membership.principal_id = target_ticket.principal_id
          AND membership.status = 'active'
          AND tenant.status = 'active'
          AND (membership.expires_at IS NULL OR membership.expires_at > now())
    ) THEN
        RAISE EXCEPTION 'tenant context option requires an active membership for the ticket principal'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.validate_token_family()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    target_principal system.principals%ROWTYPE;
BEGIN
    SELECT * INTO target_principal
    FROM system.principals
    WHERE id = NEW.principal_id
    FOR UPDATE;

    IF NEW.revoked_at IS NOT NULL
       OR target_principal.status <> 'active'
       OR NEW.issued_authorization_version <> target_principal.authorization_version THEN
        RAISE EXCEPTION 'token family requires an active principal at the current authorization version'
            USING ERRCODE = '23514';
    END IF;
    IF NEW.context_type = 'platform' THEN
        IF target_principal.principal_type = 'user' AND NEW.assurance_level NOT IN ('aal2', 'aal3') THEN
            RAISE EXCEPTION 'platform user token family requires aal2'
                USING ERRCODE = '23514';
        END IF;
        IF NOT EXISTS (
            SELECT 1
            FROM system.role_assignments assignment
            WHERE assignment.principal_id = NEW.principal_id
              AND assignment.scope_type = 'platform'
              AND assignment.status = 'active'
              AND assignment.valid_from <= now()
              AND (assignment.valid_until IS NULL OR assignment.valid_until > now())
        ) THEN
            RAISE EXCEPTION 'platform token family requires an effective platform role'
                USING ERRCODE = '23514';
        END IF;
    ELSIF NOT EXISTS (
        SELECT 1
        FROM system.tenant_memberships membership
        JOIN system.tenants tenant ON tenant.id = membership.tenant_id
        WHERE membership.id = NEW.tenant_membership_id
          AND membership.principal_id = NEW.principal_id
          AND membership.status = 'active'
          AND tenant.status = 'active'
          AND (membership.expires_at IS NULL OR membership.expires_at > now())
    ) THEN
        RAISE EXCEPTION 'tenant token family requires an active membership for the principal'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

