       OR NEW.family_id <> OLD.family_id
       OR NEW.owner <> OLD.owner
       OR NEW.expires_at <> OLD.expires_at
       OR NEW.created_at <> OLD.created_at
       OR OLD.revoked_at IS NOT NULL
       OR NEW.revoked_at IS NULL THEN
        RAISE EXCEPTION 'resource access ticket facts are immutable and revocation is one-way'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.revoke_access_token_delegations()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.revoked_at IS NULL AND NEW.revoked_at IS NOT NULL THEN
        UPDATE system.delegated_access_tokens
        SET revoked_at = NEW.revoked_at
        WHERE source_access_token_id = NEW.id
          AND revoked_at IS NULL;
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.revoke_token_family_derivatives()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.revoked_at IS NULL AND NEW.revoked_at IS NOT NULL THEN
        UPDATE system.refresh_tokens
        SET revoked_at = NEW.revoked_at
        WHERE family_id = NEW.id
          AND revoked_at IS NULL;

        UPDATE system.access_tokens
        SET revoked_at = NEW.revoked_at
        WHERE family_id = NEW.id
          AND revoked_at IS NULL;

        UPDATE system.resource_access_tickets
        SET revoked_at = NEW.revoked_at
        WHERE family_id = NEW.id
          AND revoked_at IS NULL;
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION system.prevent_token_history_delete()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION '% history cannot be physically deleted', TG_TABLE_NAME
        USING ERRCODE = '23514';
END;
$$;

