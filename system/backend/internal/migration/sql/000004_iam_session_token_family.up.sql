CREATE FUNCTION system.valid_distinct_text_array(values_to_check text[], require_nonempty boolean)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
AS $$
    SELECT values_to_check IS NOT NULL
       AND (NOT require_nonempty OR cardinality(values_to_check) > 0)
       AND NOT EXISTS (
           SELECT 1 FROM unnest(values_to_check) AS value
           WHERE value IS NULL OR btrim(value) = ''
       )
       AND cardinality(values_to_check) = (
           SELECT count(DISTINCT value)::integer FROM unnest(values_to_check) AS value
       );
$$;

