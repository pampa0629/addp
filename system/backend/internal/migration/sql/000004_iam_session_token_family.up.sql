    issued_authorization_version bigint NOT NULL CHECK (issued_authorization_version > 0),
    client_id text NOT NULL CHECK (btrim(client_id) <> ''),
    auth_type text NOT NULL CHECK (auth_type IN ('first_party', 'oauth')),
    audiences text[] NOT NULL CHECK (system.valid_distinct_text_array(audiences, true)),
    scopes text[] NOT NULL CHECK (system.valid_distinct_text_array(scopes, false)),
    authentication_methods text[] NOT NULL CHECK (system.valid_distinct_text_array(authentication_methods, true)),
    assurance_level text NOT NULL CHECK (assurance_level IN ('aal1', 'aal2', 'aal3', 'not_applicable')),
    authenticated_at timestamptz NOT NULL,
    step_up_expires_at timestamptz,
    oidc_subject text,
    oidc_acr text,
    oidc_amr text[],
    oidc_claims_schema_version smallint,
    oidc_claims jsonb,
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    revoked_reason text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
