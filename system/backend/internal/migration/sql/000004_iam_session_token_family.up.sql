    CHECK (
        (context_type = 'platform' AND tenant_membership_id IS NULL)
        OR (context_type = 'tenant' AND tenant_membership_id IS NOT NULL)
    ),
    CHECK (
        (auth_type = 'first_party'
            AND protocol_request_id IS NULL
            AND client_id = 'addp-web'
            AND audiences = ARRAY['addp.api']::text[]
            AND cardinality(scopes) = 0)
        OR (auth_type = 'oauth'
            AND protocol_request_id IS NOT NULL
            AND client_id <> 'addp-web'
            AND cardinality(scopes) > 0)
    ),
    CHECK (authenticated_at <= created_at),
    CHECK (expires_at > created_at),
    CHECK (step_up_expires_at IS NULL OR (step_up_expires_at >= authenticated_at AND step_up_expires_at <= expires_at)),
    CHECK (
        (revoked_at IS NULL AND revoked_reason IS NULL)
        OR (revoked_at IS NOT NULL AND revoked_reason IS NOT NULL AND btrim(revoked_reason) <> '')
    ),
    CHECK (revoked_at IS NULL OR revoked_at >= created_at),
    CHECK (
        (oidc_subject IS NULL
            AND oidc_acr IS NULL
            AND oidc_amr IS NULL
            AND oidc_claims_schema_version IS NULL
            AND oidc_claims IS NULL)
        OR (auth_type = 'oauth'
            AND oidc_subject IS NOT NULL
            AND btrim(oidc_subject) <> ''
            AND oidc_acr IS NOT NULL
            AND btrim(oidc_acr) <> ''
            AND oidc_amr IS NOT NULL
            AND system.valid_distinct_text_array(oidc_amr, true)
            AND oidc_claims_schema_version IS NOT NULL
            AND oidc_claims_schema_version > 0
            AND oidc_claims IS NOT NULL
            AND jsonb_typeof(oidc_claims) = 'object')
    )
);

