CREATE FUNCTION system.validate_context_selection_ticket()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    target_principal system.principals%ROWTYPE;
BEGIN
    SELECT * INTO target_principal
    FROM system.principals
    WHERE id = NEW.principal_id
    FOR KEY SHARE;

    IF target_principal.principal_type <> 'user'
       OR target_principal.status <> 'active'
       OR NEW.issued_authorization_version <> target_principal.authorization_version
       OR NEW.consumed_at IS NOT NULL THEN
        RAISE EXCEPTION 'context selection ticket requires an active user at the current authorization version'
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

