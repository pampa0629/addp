       OR NEW.issued_authorization_version IS DISTINCT FROM OLD.issued_authorization_version
       OR NEW.secret_ciphertext IS DISTINCT FROM OLD.secret_ciphertext
       OR NEW.secret_nonce IS DISTINCT FROM OLD.secret_nonce
       OR NEW.key_version IS DISTINCT FROM OLD.key_version
       OR NEW.expires_at IS DISTINCT FROM OLD.expires_at
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'MFA enrollment identity and secret facts are immutable';
    END IF;
    IF OLD.consumed_at IS NOT NULL THEN
        RAISE EXCEPTION 'consumed MFA enrollment is immutable';
    END IF;
    IF NEW.failed_attempts NOT IN (OLD.failed_attempts, OLD.failed_attempts + 1) THEN
        RAISE EXCEPTION 'MFA enrollment failed attempts must increase one at a time';
    END IF;
    IF NEW.failed_attempts = OLD.failed_attempts AND NEW.consumed_at IS NULL THEN
        RAISE EXCEPTION 'MFA enrollment update must consume it or record a failed attempt';
    END IF;
    IF NEW.failed_attempts = 5 AND NEW.consumed_at IS NULL THEN
        RAISE EXCEPTION 'MFA enrollment must terminate after five failed attempts';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_mfa_enrollments_transition
BEFORE UPDATE ON system.mfa_enrollments
FOR EACH ROW EXECUTE FUNCTION system.validate_mfa_enrollment_transition();
CREATE TRIGGER trg_mfa_enrollments_prevent_delete
BEFORE DELETE ON system.mfa_enrollments
FOR EACH ROW EXECUTE FUNCTION system.prevent_iam_security_fact_delete();
CREATE TRIGGER trg_mfa_enrollments_prevent_truncate
BEFORE TRUNCATE ON system.mfa_enrollments
FOR EACH STATEMENT EXECUTE FUNCTION system.prevent_iam_security_fact_delete();

REVOKE DELETE, TRUNCATE ON system.mfa_enrollments FROM PUBLIC;

COMMIT;
