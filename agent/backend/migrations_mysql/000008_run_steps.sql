CREATE TABLE IF NOT EXISTS agent.run_steps (
    id CHAR(32) NOT NULL,
    agent_run_id CHAR(32) NOT NULL,
    sequence INTEGER NOT NULL,
    step_type VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    protocol_invocation_id VARCHAR(100) NOT NULL,
    tool_call_id VARCHAR(100),
    tool_name VARCHAR(255),
    input JSON NOT NULL,
    output_summary LONGTEXT,
    facts JSON NOT NULL,
    error_source VARCHAR(30),
    error_code VARCHAR(100),
    error_message LONGTEXT,
    started_at DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    completed_at DATETIME(6),
    PRIMARY KEY (id),
    CONSTRAINT uq_agent_run_steps_sequence UNIQUE (agent_run_id, sequence),
    FOREIGN KEY(agent_run_id) REFERENCES agent.runs (id) ON DELETE CASCADE,
    KEY ix_agent_run_steps_agent_run_id (`agent_run_id`),
    KEY ix_agent_run_steps_status (`status`),
    KEY ix_agent_run_steps_tool_call_id (`tool_call_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
