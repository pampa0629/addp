CREATE TABLE IF NOT EXISTS agent.interactions (
    id CHAR(32) NOT NULL,
    session_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,
    tenant_id INTEGER NOT NULL,
    agent_run_id CHAR(32) NOT NULL,
    tool_call_id VARCHAR(100),
    owner_interaction_id VARCHAR(100),
    owner_request_fingerprint VARCHAR(64),
    open_url LONGTEXT,
    request_summary JSON NOT NULL,
    kind VARCHAR(50) NOT NULL,
    owner VARCHAR(50) NOT NULL,
    status VARCHAR(30) NOT NULL,
    prompt LONGTEXT NOT NULL,
    response_schema JSON NOT NULL,
    options JSON NOT NULL,
    answer JSON,
    created_at DATETIME(6) NOT NULL DEFAULT (UTC_TIMESTAMP(6)),
    completed_at DATETIME(6),
    expires_at DATETIME(6),
    PRIMARY KEY (id),
    FOREIGN KEY(session_id) REFERENCES agent.sessions (id) ON DELETE CASCADE,
    FOREIGN KEY(agent_run_id) REFERENCES agent.runs (id) ON DELETE CASCADE,
    KEY ix_agent_interactions_agent_run_id (`agent_run_id`),
    KEY ix_agent_interactions_owner_interaction_id (`owner_interaction_id`),
    KEY ix_agent_interactions_session_id (`session_id`),
    KEY ix_agent_interactions_status (`status`),
    KEY ix_agent_interactions_tenant_id (`tenant_id`),
    KEY ix_agent_interactions_user_id (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
