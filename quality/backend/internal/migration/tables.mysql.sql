CREATE TABLE IF NOT EXISTS issue_actions (
    `id` bigint NOT NULL AUTO_INCREMENT,
    `tenant_id` bigint NOT NULL,
    `issue_id` bigint NOT NULL,
    `plan_id` bigint NOT NULL,
    `execution_id` LONGTEXT NOT NULL,
    `action` LONGTEXT NOT NULL,
    `actor_id` bigint,
    `note` LONGTEXT NOT NULL,
    `accepted_count` bigint DEFAULT 0 NOT NULL,
    `evidence` JSON,
    `created_at` DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    KEY idx_quality_issue_actions_history (tenant_id, issue_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS plans (
    `id` bigint NOT NULL AUTO_INCREMENT,
    `tenant_id` bigint NOT NULL,
    `code` VARCHAR(100) NOT NULL,
    `name` VARCHAR(200) NOT NULL,
    `description` LONGTEXT DEFAULT ('') NOT NULL,
    `version` bigint DEFAULT 1 NOT NULL,
    `table_bindings` JSON NOT NULL,
    `created_by` bigint NOT NULL,
    `updated_by` bigint NOT NULL,
    `created_at` DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6) NOT NULL,
    `updated_at` DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6) NOT NULL,
    `last_run_at` DATETIME(6),
    `last_execution_id` VARCHAR(64) DEFAULT '' NOT NULL,
    `last_execution_status` VARCHAR(20) DEFAULT '' NOT NULL,
    `owner_domain_id` bigint,
    PRIMARY KEY (id),
    UNIQUE KEY plans_tenant_id_code_key (tenant_id, code),
    UNIQUE KEY plans_tenant_id_id_key (tenant_id, id),
    KEY idx_quality_plans_owner_domain (tenant_id, owner_domain_id),
    KEY idx_quality_plans_tenant_updated (tenant_id, updated_at DESC, id DESC),
    CONSTRAINT plans_code_check CHECK (((code) REGEXP '^[a-z][a-z0-9_]*$')),
    CONSTRAINT plans_table_bindings_check CHECK ((JSON_TYPE(table_bindings) = 'ARRAY')),
    CONSTRAINT plans_version_check CHECK ((version > 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS rules (
    `id` bigint NOT NULL AUTO_INCREMENT,
    `tenant_id` bigint NOT NULL,
    `code` VARCHAR(100) NOT NULL,
    `version` bigint DEFAULT 1 NOT NULL,
    `revision_no` bigint DEFAULT 1 NOT NULL,
    `name` VARCHAR(200) NOT NULL,
    `description` LONGTEXT DEFAULT ('') NOT NULL,
    `type` VARCHAR(40) NOT NULL,
    `params` JSON NOT NULL,
    `source` JSON,
    `created_by` bigint NOT NULL,
    `updated_by` bigint NOT NULL,
    `created_at` DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6) NOT NULL,
    `updated_at` DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6) NOT NULL,
    `owner_domain_id` bigint,
    PRIMARY KEY (id),
    UNIQUE KEY rules_tenant_id_code_key (tenant_id, code),
    UNIQUE KEY rules_tenant_id_id_key (tenant_id, id),
    KEY idx_quality_rules_owner_domain (tenant_id, owner_domain_id),
    KEY idx_quality_rules_tenant_updated (tenant_id, updated_at DESC, id DESC),
    CONSTRAINT rules_code_check CHECK (((code) REGEXP '^[a-z][a-z0-9_]*$')),
    CONSTRAINT rules_params_check CHECK ((JSON_TYPE(params) = 'OBJECT')),
    CONSTRAINT rules_revision_no_check CHECK ((revision_no > 0)),
    CONSTRAINT rules_version_check CHECK ((version > 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS standard_reference_guards (
    `id` bigint NOT NULL AUTO_INCREMENT,
    `tenant_id` bigint NOT NULL,
    `resource_type` VARCHAR(32) NOT NULL,
    `resource_id` bigint NOT NULL,
    `state` VARCHAR(16) DEFAULT 'open' NOT NULL,
    `created_at` DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6) NOT NULL,
    `updated_at` DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_quality_standard_reference_guard (tenant_id, resource_type, resource_id),
    CONSTRAINT ck_quality_standard_reference_guard_resource_type CHECK ((resource_type = 'domain')),
    CONSTRAINT ck_quality_standard_reference_guard_state CHECK ((state IN ('open', 'frozen', 'deleted')))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS issues (
    `id` bigint NOT NULL AUTO_INCREMENT,
    `tenant_id` bigint NOT NULL,
    `execution_id` VARCHAR(255) NOT NULL,
    `last_execution_id` VARCHAR(255) NOT NULL,
    `plan_id` bigint NOT NULL,
    `rule_type` VARCHAR(100) NOT NULL,
    `severity` VARCHAR(20) DEFAULT 'error' NOT NULL,
    `message` LONGTEXT DEFAULT ('') NOT NULL,
    `column_name` LONGTEXT NOT NULL,
    `table_name` VARCHAR(200) NOT NULL,
    `schema_name` VARCHAR(200) NOT NULL,
    `engine_id` bigint NOT NULL,
    `failed_count` bigint NOT NULL,
    `total_count` bigint NOT NULL,
    `pass_rate` double precision NOT NULL,
    `detail` JSON,
    `status` VARCHAR(50) DEFAULT 'open' NOT NULL,
    `resolved_at` DATETIME(6),
    `resolved_by` bigint,
    `resolution_note` LONGTEXT DEFAULT ('') NOT NULL,
    `last_observed_at` DATETIME(6),
    `created_at` DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6) NOT NULL,
    `updated_at` DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6) NOT NULL,
    `rule_key` CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
    `owner_domain_id` bigint,
    `target_key` VARCHAR(64),
    `version` bigint DEFAULT 1 NOT NULL,
    `evidence` JSON,
    `accepted_keys` JSON,
    `evidence_reason` LONGTEXT DEFAULT ('not_observed') NOT NULL,
    `accepted_count` bigint DEFAULT 0 NOT NULL,
    `pending_count` bigint DEFAULT 0 NOT NULL,
    PRIMARY KEY (id),
    KEY idx_quality_issues_execution_id (execution_id),
    KEY idx_quality_issues_last_execution_id (last_execution_id),
    KEY idx_quality_issues_owner_domain (tenant_id, owner_domain_id),
    KEY idx_quality_issues_tenant_engine_updated (tenant_id, engine_id, updated_at DESC, id DESC),
    KEY idx_quality_issues_tenant_status_engine_updated (tenant_id, status, engine_id, updated_at DESC, id DESC),
    KEY idx_quality_issues_tenant_status_updated (tenant_id, status, updated_at DESC, id DESC),
    KEY idx_quality_issues_tenant_updated (tenant_id, updated_at DESC, id DESC),
    UNIQUE KEY uq_quality_issue_rule (tenant_id, plan_id, target_key, rule_key),
    CONSTRAINT fk_quality_issue_plan FOREIGN KEY (tenant_id, plan_id) REFERENCES plans(tenant_id, id) ON DELETE CASCADE,
    CHECK (IS_UUID(rule_key) AND LENGTH(rule_key)=36),
    CONSTRAINT ck_quality_issue_counts CHECK (((failed_count >= 0) AND (total_count >= 0) AND ((pass_rate >= (0)) AND (pass_rate <= (100))))),
    CONSTRAINT issues_accepted_count_check CHECK ((accepted_count >= 0)),
    CONSTRAINT issues_pending_count_check CHECK ((pending_count >= 0)),
    CONSTRAINT issues_version_check CHECK ((version > 0)),
    CONSTRAINT quality_issues_status_check CHECK (((status) IN ('open', 'resolved', 'ignored', 'accepted')))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS rule_revisions (
    `tenant_id` bigint NOT NULL,
    `rule_id` bigint NOT NULL,
    `revision_no` bigint NOT NULL,
    `name` VARCHAR(200) NOT NULL,
    `description` LONGTEXT DEFAULT ('') NOT NULL,
    `type` VARCHAR(40) NOT NULL,
    `params` JSON NOT NULL,
    `source` JSON,
    `created_at` DATETIME(6) DEFAULT CURRENT_TIMESTAMP(6) NOT NULL,
    `created_by` bigint NOT NULL,
    PRIMARY KEY (tenant_id, rule_id, revision_no),
    CONSTRAINT rule_revisions_tenant_id_rule_id_fkey FOREIGN KEY (tenant_id, rule_id) REFERENCES rules(tenant_id, id),
    CONSTRAINT rule_revisions_params_check CHECK ((JSON_TYPE(params) = 'OBJECT')),
    CONSTRAINT rule_revisions_revision_no_check CHECK ((revision_no > 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS plan_check_items (
    `tenant_id` bigint NOT NULL,
    `plan_id` bigint NOT NULL,
    `rule_key` CHAR(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL,
    `position` integer NOT NULL,
    `rule_id` bigint NOT NULL,
    `revision_no` bigint NOT NULL,
    `bindings` JSON NOT NULL,
    `severity` VARCHAR(10) NOT NULL,
    `disabled` boolean DEFAULT false NOT NULL,
    PRIMARY KEY (tenant_id, plan_id, rule_key),
    UNIQUE KEY plan_check_items_tenant_id_plan_id_position_key (tenant_id, plan_id, `position`),
    KEY idx_quality_plan_items_rule (tenant_id, rule_id, plan_id),
    CONSTRAINT plan_check_items_tenant_id_plan_id_fkey FOREIGN KEY (tenant_id, plan_id) REFERENCES plans(tenant_id, id) ON DELETE CASCADE,
    CONSTRAINT plan_check_items_tenant_id_rule_id_revision_no_fkey FOREIGN KEY (tenant_id, rule_id, revision_no) REFERENCES rule_revisions(tenant_id, rule_id, revision_no),
    CHECK (IS_UUID(rule_key) AND LENGTH(rule_key)=36),
    CONSTRAINT plan_check_items_bindings_check CHECK ((JSON_TYPE(bindings) = 'OBJECT')),
    CONSTRAINT plan_check_items_position_check CHECK ((`position` >= 0)),
    CONSTRAINT plan_check_items_severity_check CHECK (((severity) IN ('error', 'warning', 'info')))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
