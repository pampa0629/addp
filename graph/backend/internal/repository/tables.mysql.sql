CREATE TABLE IF NOT EXISTS knowledge_graphs (
    `admission_reconciled_by` bigint,
    `admission_reconciliation_digest` varchar(64),
    `id` bigint NOT NULL AUTO_INCREMENT,
    `version` bigint DEFAULT 1 NOT NULL,
    `admission_closed` boolean DEFAULT false NOT NULL,
    `admission_cause` longtext,
    `admission_execution_id` varchar(64),
    `admission_reconciled_at` datetime(6),
    `physical_target_identity` longtext,
    `tenant_id` bigint NOT NULL,
    `ontology_id` bigint NOT NULL,
    `engine_id` bigint NOT NULL,
    `catalog_path` json NOT NULL,
    `index_management` longtext NOT NULL,
    `name` longtext NOT NULL,
    `description` longtext,
    `status` longtext DEFAULT ('active'),
    `is_public` boolean DEFAULT false,
    `stats` json DEFAULT ('{}'),
    `created_at` datetime(6),
    `updated_at` datetime(6),
    PRIMARY KEY (id),
    catalog_path_digest BINARY(32) GENERATED ALWAYS AS (UNHEX(SHA2(CAST(catalog_path AS CHAR CHARACTER SET utf8mb4), 256))) STORED,
    UNIQUE KEY idx_graph_target (tenant_id, engine_id, catalog_path_digest),
    KEY idx_knowledge_graphs_ontology_id (ontology_id),
    KEY idx_knowledge_graphs_tenant_id (tenant_id),
    CONSTRAINT fk_knowledge_graphs_ontology FOREIGN KEY (ontology_id) REFERENCES ontologies(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

