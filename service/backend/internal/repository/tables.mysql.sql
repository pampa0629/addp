CREATE TABLE IF NOT EXISTS catalog_resource_changes (
    `id` bigint NOT NULL AUTO_INCREMENT,
    `tenant_id` bigint NOT NULL,
    `source_type` varchar(32) NOT NULL,
    `source_identity` bigint NOT NULL,
    `operation` varchar(16) NOT NULL,
    `snapshot` json NOT NULL,
    `observed_at` datetime(6) NOT NULL,
    PRIMARY KEY (id),
    KEY idx_service_catalog_changes_source (tenant_id, source_type, source_identity),
    KEY idx_service_catalog_changes_tenant_id (tenant_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

