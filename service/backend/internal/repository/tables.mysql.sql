CREATE TABLE IF NOT EXISTS query_services (
    `id` bigint NOT NULL AUTO_INCREMENT,
    `version` bigint DEFAULT 1 NOT NULL,
    `tenant_id` bigint NOT NULL,
    `service_name` varchar(255) NOT NULL,
    `title` varchar(255) NOT NULL,
    `description` longtext,
    `keywords` json,
    `config_type` varchar(50) NOT NULL,
    `engine_id` bigint,
    `runtime_engine_id` bigint,
    `schema_name` varchar(255),
    `table_name` varchar(255),
    `sql_query` longtext,
    `named_parameters` json DEFAULT ('[]') NOT NULL,
    `data_config` json DEFAULT ('{}') NOT NULL,
    `protocols` json DEFAULT ('{"rest_api": {"enabled": true, "formats": ["json", "csv", "geojson"]}, "ogc_features": {"enabled": false, "version": "1.0"}}') NOT NULL,
    `public_access` boolean DEFAULT false,
    `max_features` bigint DEFAULT 1000,
    `status` varchar(50) DEFAULT 'active',
    `error_message` longtext,
    `created_by` bigint NOT NULL,
    `created_at` datetime(6),
    `updated_at` datetime(6),
    CONSTRAINT chk_query_service_version CHECK ((version > 0)),
    CONSTRAINT chk_service_query_services_status CHECK (status IN ('active', 'inactive', 'error')),
    CONSTRAINT query_services_config_type_check CHECK (config_type IN ('table', 'sql', 'analytical')),
    CONSTRAINT query_services_explicit_execution_engine_check CHECK (((((config_type) = 'table') AND (engine_id IS NOT NULL)) OR (((config_type) = 'sql') AND ((engine_id IS NOT NULL) <> (runtime_engine_id IS NOT NULL))) OR (((config_type) = 'analytical') AND (engine_id IS NULL) AND (runtime_engine_id IS NULL) AND (COALESCE(sql_query, '') = '') AND ((COALESCE(schema_name, '')) = '') AND ((COALESCE(table_name, '')) = '') AND (JSON_LENGTH(named_parameters)=0 AND JSON_TYPE(named_parameters)='ARRAY')))),
    PRIMARY KEY (id),
    KEY idx_query_services_config_type (config_type),
    KEY idx_query_services_engine (engine_id),
    KEY idx_query_services_runtime_engine (runtime_engine_id),
    KEY idx_query_services_status (status),
    KEY idx_query_services_tenant (tenant_id),
    UNIQUE KEY unique_query_service_name (service_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

CREATE TABLE IF NOT EXISTS registered_services (
    `id` bigint NOT NULL AUTO_INCREMENT,
    `tenant_id` bigint NOT NULL,
    `service_name` varchar(255) NOT NULL,
    `title` varchar(255) NOT NULL,
    `description` longtext,
    `keywords` json,
    `service_type` varchar(50) NOT NULL,
    `endpoint_url` longtext NOT NULL,
    `metadata` json DEFAULT ('{}'),
    `auth_type` varchar(50) DEFAULT 'none',
    `auth_config` json DEFAULT ('{}'),
    `health_check_url` longtext,
    `last_checked_at` datetime(6),
    `status` varchar(50) DEFAULT 'active',
    `error_message` longtext,
    `created_by` bigint NOT NULL,
    `created_at` datetime(6),
    `updated_at` datetime(6),
    CONSTRAINT chk_service_registered_services_auth_type CHECK (auth_type IN ('none', 'basic', 'bearer', 'api_key')),
    CONSTRAINT chk_service_registered_services_service_type CHECK (service_type IN ('wms', 'wfs', 'wmts', 'ogc_api', 'xyz', 'rest')),
    CONSTRAINT chk_service_registered_services_status CHECK (status IN ('active', 'inactive', 'error')),
    PRIMARY KEY (id),
    KEY idx_registered_services_status (status),
    KEY idx_registered_services_tenant (tenant_id),
    KEY idx_registered_services_type (service_type),
    UNIQUE KEY unique_registered_service_name (service_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;

