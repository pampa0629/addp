    `to_revision` bigint NOT NULL,
    `status` VARCHAR(20) NOT NULL,
    `applied_by` bigint,
    `detected_at` DATETIME(6) NOT NULL,
    `applied_at` DATETIME(6),
    `metadata_scan_status` VARCHAR(20) DEFAULT '' NOT NULL,
    `metadata_scan_claim_token` VARCHAR(36) DEFAULT '' NOT NULL,
    `metadata_scan_lease_until` DATETIME(6),
