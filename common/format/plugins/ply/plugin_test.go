func TestDescribeGaussianSplatReadsPLYHeader(t *testing.T) {
	var content bytes.Buffer
	content.WriteString(`ply
format binary_little_endian 1.0
comment Generated by P3BJet GaussianSplats
element vertex 2
property float x
property float y
property float z
property float f_dc_0
property float f_dc_1
property float f_dc_2
property float opacity
property float scale_0
property float scale_1
property float scale_2
property float rot_0
property float rot_1
property float rot_2
property float rot_3
end_header
`)
	writePLYGaussianVertex(&content, -2, 3, 100)
	writePLYGaussianVertex(&content, 5, -7, 120)
	result, err := NewPlugin().DescribeGaussianSplat(context.Background(), format.GaussianSplatDescribeInput{
		Reader: bytes.NewReader(content.Bytes()),
	}, nil)
	if err != nil {
		t.Fatalf("DescribeGaussianSplat() error = %v", err)
	}
	if result == nil || result.GaussianSplat == nil {
		t.Fatalf("DescribeGaussianSplat() = %#v, want Gaussian splat info", result)
	}
	if result.GaussianSplat.Representation != datatype.GaussianSplatRepresentation3DGS {
		t.Fatalf("Representation = %q, want 3d_gaussian_splatting", result.GaussianSplat.Representation)
	}
	if result.GaussianSplat.SplatCount == nil || *result.GaussianSplat.SplatCount != 2 {
		t.Fatalf("SplatCount = %v, want 2", result.GaussianSplat.SplatCount)
	}
	if result.GaussianSplat.HasScale == nil || !*result.GaussianSplat.HasScale {
		t.Fatalf("HasScale = %v, want true", result.GaussianSplat.HasScale)
	}
	assertPLYBounds(t, result.GaussianSplat.Bounds3D, -2, -7, 100, 5, 3, 120)
	if result.FormatInfo["encoding"] != "binary_little_endian" {
		t.Fatalf("format_info = %#v, want binary_little_endian", result.FormatInfo)
	}
	if result.FormatInfo["is_gaussian_splat"] != true {
		t.Fatalf("is_gaussian_splat = %#v, want true", result.FormatInfo["is_gaussian_splat"])
	}
	if result.FormatInfo["layout"] != "gaussian_splat" {
		t.Fatalf("layout = %#v, want gaussian_splat", result.FormatInfo["layout"])
	}
}

