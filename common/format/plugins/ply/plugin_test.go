func TestDescribeGaussianSplatSamplesLargeBinaryPLYBounds(t *testing.T) {
	var content bytes.Buffer
	content.WriteString(`ply
format binary_little_endian 1.0
comment Generated by P3BJet GaussianSplats
element vertex 100001
property float x
property float y
property float z
property float f_dc_0
property float f_dc_1
property float f_dc_2
property float opacity
property float scale_0
property float scale_1
property float scale_2
property float rot_0
property float rot_1
property float rot_2
property float rot_3
end_header
`)
	writePLYGaussianVertex(&content, -2, 3, 100)
	for i := int64(1); i < maxExactPLYBoundsVertices; i++ {
		writePLYGaussianVertex(&content, 0, 0, 110)
	}
	writePLYGaussianVertex(&content, 5, -7, 120)
	reader := plyMemoryRangeReader{content: content.Bytes()}

	result, err := NewPlugin().DescribeGaussianSplat(context.Background(), format.GaussianSplatDescribeInput{
		Reader:      bytes.NewReader(content.Bytes()),
		RangeReader: reader,
		Ref:         contentio.NewRef("site.ply", contentio.RoleMain),
		SizeBytes:   int64(content.Len()),
	}, nil)
	if err != nil {
		t.Fatalf("DescribeGaussianSplat() error = %v", err)
	}
	if result == nil || result.GaussianSplat == nil {
		t.Fatalf("DescribeGaussianSplat() = %#v, want Gaussian splat info", result)
	}
	assertPLYBounds(t, result.GaussianSplat.SampledBounds3D, -2, -7, 100, 5, 3, 120)
	if result.GaussianSplat.Bounds3D != nil {
		t.Fatalf("Bounds3D = %#v, want nil for sampled large PLY", result.GaussianSplat.Bounds3D)
	}
	if result.GaussianSplat.SampledBoundsMethod != "sampled_binary_vertices" {
		t.Fatalf("SampledBoundsMethod = %q, want sampled_binary_vertices", result.GaussianSplat.SampledBoundsMethod)
	}
	if result.GaussianSplat.SampledBoundsSampleCount == nil || *result.GaussianSplat.SampledBoundsSampleCount != plySampledBoundsSampleCount {
		t.Fatalf("SampledBoundsSampleCount = %v, want %d", result.GaussianSplat.SampledBoundsSampleCount, plySampledBoundsSampleCount)
	}
}

