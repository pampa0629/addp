package authorization

import (
	"bytes"
	"crypto/sha256"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const IAMCatalogSeedRelativePath = "system/backend/internal/migration/sql/000006_iam_catalog_seed.up.sql"
const IAMCatalogSeedSHA256 = "84013560508017c7e5121ae6fafc6d663d1d02404b5b4bb0c4af6dc64dbae4e2"

var platformAdministratorConflictRoleKeys = []string{
	"platform.audit_administrator",
	"platform.security_administrator",
	"platform.system_administrator",
}

func GenerateIAMCatalogSeedSQL(report AuthorizationCatalogReport) ([]byte, error) {
	if report.SchemaVersion != AuthorizationCatalogReportSchemaVersion {
		return nil, fmt.Errorf("schema_version must be %q", AuthorizationCatalogReportSchemaVersion)
	}
	if len(report.Permissions) == 0 {
		return nil, fmt.Errorf("permission catalog must not be empty")
	}
	if len(report.Roles) == 0 {
		return nil, fmt.Errorf("builtin role catalog must not be empty")
	}

	permissions := append([]PermissionDescriptor(nil), report.Permissions...)
	roles := append([]BuiltinRoleDescriptor(nil), report.Roles...)
	sort.Slice(permissions, func(i, j int) bool { return permissions[i].Key < permissions[j].Key })
	sort.Slice(roles, func(i, j int) bool { return roles[i].Key < roles[j].Key })
	if err := validateCatalogSeedInputs(permissions, roles); err != nil {
		return nil, err
	}

	var output strings.Builder
	output.WriteString("-- Code generated by the ADDP authorization manifest aggregator. DO NOT EDIT.\n")
	fmt.Fprintf(&output, "-- Permission manifests: %s\n", permissionManifestVersions(report.PermissionManifests))
	fmt.Fprintf(&output, "-- Builtin role manifest version: %d\n\n", report.BuiltinRoleManifest.ManifestVersion)
	output.WriteString("BEGIN;\n\n")
	writePermissionSeed(&output, permissions)
	writeRoleSeed(&output, roles)
	writeRolePermissionSeed(&output, roles)
	writePlatformRoleConflictSeed(&output)
	writeBuiltinOAuthClientSeed(&output)
	output.WriteString("COMMIT;\n")
	return []byte(output.String()), nil
}

func WriteGeneratedIAMCatalogSeed(repositoryRoot string, data []byte) error {
	path, err := catalogSeedPath(repositoryRoot)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("create IAM catalog seed directory: %w", err)
	}
	if err := os.WriteFile(path, data, 0o644); err != nil {
		return fmt.Errorf("write IAM catalog seed: %w", err)
	}
	return nil
}

func CheckGeneratedIAMCatalogSeed(repositoryRoot string, expected []byte) error {
	path, err := catalogSeedPath(repositoryRoot)
	if err != nil {
		return err
	}
	actual, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("read IAM catalog seed: %w", err)
	}
	if !bytes.Equal(actual, expected) {
		return fmt.Errorf("generated IAM catalog seed is stale: run authorization-generate")
	}
	return nil
}

// CheckImmutableIAMCatalogSeed protects the published bootstrap migration from
// being regenerated when later Manifest versions add forward-only catalog changes.
func CheckImmutableIAMCatalogSeed(repositoryRoot string) error {
	path, err := catalogSeedPath(repositoryRoot)
	if err != nil {
		return err
	}
	actual, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("read IAM catalog seed: %w", err)
	}
	digest := fmt.Sprintf("%x", sha256.Sum256(actual))
	if digest != IAMCatalogSeedSHA256 {
		return fmt.Errorf("published IAM catalog seed digest = %s, want %s", digest, IAMCatalogSeedSHA256)
	}
	return nil
}

func catalogSeedPath(repositoryRoot string) (string, error) {
	if repositoryRoot == "" {
		return "", fmt.Errorf("repository root must not be empty")
	}
	root, err := filepath.Abs(repositoryRoot)
	if err != nil {
		return "", fmt.Errorf("resolve repository root: %w", err)
	}
	return filepath.Join(root, filepath.FromSlash(IAMCatalogSeedRelativePath)), nil
}

func validateCatalogSeedInputs(permissions []PermissionDescriptor, roles []BuiltinRoleDescriptor) error {
	permissionKeys := make(map[string]struct{}, len(permissions))
	previousPermission := ""
	for _, permission := range permissions {
		if permission.Key == "" || permission.Key == previousPermission {
			return fmt.Errorf("permission catalog contains an empty or duplicate key %q", permission.Key)
		}
		permissionKeys[permission.Key] = struct{}{}
		previousPermission = permission.Key
	}

	roleKeys := make(map[string]struct{}, len(roles))
	previousRole := ""
	for _, role := range roles {
		if role.Key == "" || role.Key == previousRole {
			return fmt.Errorf("builtin role catalog contains an empty or duplicate key %q", role.Key)
		}
		for _, permissionKey := range role.Permissions {
			if _, exists := permissionKeys[permissionKey]; !exists {
				return fmt.Errorf("role %q references unknown permission %q", role.Key, permissionKey)
			}
		}
		roleKeys[role.Key] = struct{}{}
		previousRole = role.Key
	}
	for _, roleKey := range platformAdministratorConflictRoleKeys {
		if _, exists := roleKeys[roleKey]; !exists {
			return fmt.Errorf("platform administrator conflict role %q is missing", roleKey)
		}
	}
	return nil
}

func permissionManifestVersions(references []PermissionManifestReference) string {
	canonical := append([]PermissionManifestReference(nil), references...)
	sort.Slice(canonical, func(i, j int) bool { return canonical[i].OwnerModule < canonical[j].OwnerModule })
	parts := make([]string, 0, len(canonical))
	for _, reference := range canonical {
		parts = append(parts, fmt.Sprintf("%s=%d", reference.OwnerModule, reference.ManifestVersion))
	}
	return strings.Join(parts, ", ")
}

func writePermissionSeed(output *strings.Builder, permissions []PermissionDescriptor) {
	output.WriteString("INSERT INTO system.permissions (\n")
	output.WriteString("    permission_key, owner_module, action, risk_level, delegable, allowed_scope_types,\n")
	output.WriteString("    tenant_customizable, name_i18n_key, description_i18n_key, status\n")
	output.WriteString(") VALUES\n")
	for index, permission := range permissions {
		separator := ","
		if index == len(permissions)-1 {
			separator = ";"
		}
		fmt.Fprintf(output, "    (%s, %s, %s, %s, %t, %s, %t, %s, %s, %s)%s\n",
			sqlText(permission.Key),
			sqlText(permission.OwnerModule),
			sqlText(permission.Action),
			sqlText(permission.RiskLevel),
			permission.Delegable,
			sqlTextArray(permission.AllowedScopeTypes),
			permission.TenantCustomizable,
			sqlText(permission.NameI18nKey),
			sqlText(permission.DescriptionI18nKey),
			sqlText(permission.Status),
			separator,
		)
	}
	output.WriteString("\n")
}

func writeRoleSeed(output *strings.Builder, roles []BuiltinRoleDescriptor) {
	output.WriteString("INSERT INTO system.roles (\n")
	output.WriteString("    tenant_id, role_key, name, description, name_i18n_key, description_i18n_key, role_type,\n")
	output.WriteString("    allowed_scope_types, allowed_principal_types, immutable, status, created_by_principal_id\n")
	output.WriteString(") VALUES\n")
	for index, role := range roles {
		separator := ","
		if index == len(roles)-1 {
			separator = ";"
		}
		fmt.Fprintf(output, "    (NULL, %s, NULL, NULL, %s, %s, %s, %s, %s, true, 'active', NULL)%s\n",
			sqlText(role.Key),
			sqlText(role.NameI18nKey),
			sqlText(role.DescriptionI18nKey),
			sqlText(role.RoleType),
			sqlTextArray(role.AllowedScopeTypes),
			sqlTextArray(role.AllowedPrincipalTypes),
			separator,
		)
	}
	output.WriteString("\n")
}

func writeRolePermissionSeed(output *strings.Builder, roles []BuiltinRoleDescriptor) {
	type rolePermission struct {
		roleKey       string
		permissionKey string
	}
	pairs := make([]rolePermission, 0)
	for _, role := range roles {
		for _, permissionKey := range role.Permissions {
			pairs = append(pairs, rolePermission{roleKey: role.Key, permissionKey: permissionKey})
		}
	}
	sort.Slice(pairs, func(i, j int) bool {
		if pairs[i].roleKey == pairs[j].roleKey {
			return pairs[i].permissionKey < pairs[j].permissionKey
		}
		return pairs[i].roleKey < pairs[j].roleKey
	})

	output.WriteString("INSERT INTO system.role_permissions (role_id, permission_id, source_type, created_by_principal_id)\n")
	output.WriteString("SELECT role.id, permission.id, 'product', NULL\n")
	output.WriteString("FROM (VALUES\n")
	for index, pair := range pairs {
		separator := ","
		if index == len(pairs)-1 {
			separator = ""
		}
		fmt.Fprintf(output, "    (%s, %s)%s\n", sqlText(pair.roleKey), sqlText(pair.permissionKey), separator)
	}
	output.WriteString(") AS seed(role_key, permission_key)\n")
	output.WriteString("JOIN system.roles role ON role.tenant_id IS NULL AND role.role_key = seed.role_key\n")
	output.WriteString("JOIN system.permissions permission ON permission.permission_key = seed.permission_key\n")
	output.WriteString("ORDER BY seed.role_key, seed.permission_key;\n\n")
}

func writePlatformRoleConflictSeed(output *strings.Builder) {
	pairs := [][2]string{
		{platformAdministratorConflictRoleKeys[0], platformAdministratorConflictRoleKeys[1]},
		{platformAdministratorConflictRoleKeys[0], platformAdministratorConflictRoleKeys[2]},
		{platformAdministratorConflictRoleKeys[1], platformAdministratorConflictRoleKeys[2]},
	}
	output.WriteString("INSERT INTO system.role_conflicts (role_id_low, role_id_high, reason)\n")
	output.WriteString("SELECT LEAST(low_role.id, high_role.id), GREATEST(low_role.id, high_role.id),\n")
	output.WriteString("       'platform_three_administrators_separation_of_duties'\n")
	output.WriteString("FROM (VALUES\n")
	for index, pair := range pairs {
		separator := ","
		if index == len(pairs)-1 {
			separator = ""
		}
		fmt.Fprintf(output, "    (%s, %s)%s\n", sqlText(pair[0]), sqlText(pair[1]), separator)
	}
	output.WriteString(") AS seed(low_role_key, high_role_key)\n")
	output.WriteString("JOIN system.roles low_role ON low_role.tenant_id IS NULL AND low_role.role_key = seed.low_role_key\n")
	output.WriteString("JOIN system.roles high_role ON high_role.tenant_id IS NULL AND high_role.role_key = seed.high_role_key\n")
	output.WriteString("ORDER BY seed.low_role_key, seed.high_role_key;\n\n")
}

func writeBuiltinOAuthClientSeed(output *strings.Builder) {
	output.WriteString("INSERT INTO system.oauth_clients (\n")
	output.WriteString("    client_id, display_name, client_type, client_secret_hash, redirect_uris, grant_types,\n")
	output.WriteString("    response_types, allowed_scopes, allowed_audiences, token_endpoint_auth_method,\n")
	output.WriteString("    jwks_uri, jwks, request_uris, id_token_signed_response_alg, status\n")
	output.WriteString(") VALUES (\n")
	output.WriteString("    'addp-cli', 'ADDP CLI', 'public', NULL, ARRAY['http://127.0.0.1/callback']::text[],\n")
	output.WriteString("    ARRAY['authorization_code', 'refresh_token', 'urn:ietf:params:oauth:grant-type:device_code']::text[],\n")
	output.WriteString("    ARRAY['code']::text[], ARRAY['addp.api']::text[], ARRAY['addp.api']::text[], 'none',\n")
	output.WriteString("    NULL, NULL, ARRAY[]::text[], NULL, 'active'\n")
	output.WriteString(");\n\n")
}

func sqlText(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "''") + "'"
}

func sqlTextArray(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, sqlText(value))
	}
	return "ARRAY[" + strings.Join(quoted, ", ") + "]::text[]"
}
