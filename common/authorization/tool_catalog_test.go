func TestGenerateSystemToolAuthorizationCatalogIsDeterministic(t *testing.T) {
	root := t.TempDir()
	writeCoverageFixture(t, root, "common-python/addp_common/tools/manifest.json", `{
  "tools": [{
    "name": "data.search",
    "owner": "manager",
    "auth": {
      "audience": "manager",
      "required_scopes": ["data.search"],
      "required_permissions": ["manager.search.execute", "manager.data_item.read"]
    }
  }]
}`)
	report := AuthorizationCatalogReport{
		SchemaVersion:       AuthorizationCatalogReportSchemaVersion,
		PermissionManifests: []PermissionManifestReference{{OwnerModule: "manager"}},
		Permissions: []PermissionDescriptor{
			{Key: "manager.data_item.read", OwnerModule: "manager", Status: "active", Delegable: true},
			{Key: "manager.search.execute", OwnerModule: "manager", Status: "active", Delegable: true},
		},
	}

	first, err := GenerateSystemToolAuthorizationCatalog(root, report)
	if err != nil {
		t.Fatal(err)
	}
	second, err := GenerateSystemToolAuthorizationCatalog(root, report)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(first, second) {
		t.Fatal("generated Tool authorization catalog is not deterministic")
	}
	for _, fragment := range []string{
		"Code generated by common/authorization/cmd/manifest",
		`"data.search": {`,
		`RequiredScopes:      []string{"data.search"}`,
		`RequiredPermissions: []string{"manager.data_item.read", "manager.search.execute"}`,
		"append([]string(nil), tool.RequiredPermissions...)",
	} {
		if !strings.Contains(string(first), fragment) {
			t.Fatalf("generated catalog missing %q:\n%s", fragment, first)
		}
	}

	if err := WriteGeneratedSystemToolAuthorizationCatalog(root, first); err != nil {
		t.Fatal(err)
	}
	if err := CheckGeneratedSystemToolAuthorizationCatalog(root, first); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(root, filepath.FromSlash(SystemToolAuthorizationCatalogRelativePath))
	if err := os.WriteFile(path, append(first, '\n'), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := CheckGeneratedSystemToolAuthorizationCatalog(root, first); err == nil {
		t.Fatal("stale generated Tool authorization catalog was accepted")
	}
}

func TestGenerateSystemToolAuthorizationCatalogRejectsInvalidMapping(t *testing.T) {
	root := t.TempDir()
	writeCoverageFixture(t, root, "common-python/addp_common/tools/manifest.json", `{
  "tools": [{
    "name": "data.search",
    "owner": "manager",
    "auth": {
      "audience": "meta",
      "required_scopes": ["data.search"],
      "required_permissions": ["manager.search.execute"]
    }
  }]
}`)
	report := AuthorizationCatalogReport{
		SchemaVersion:       AuthorizationCatalogReportSchemaVersion,
		PermissionManifests: []PermissionManifestReference{{OwnerModule: "manager"}},
		Permissions: []PermissionDescriptor{{
			Key: "manager.search.execute", OwnerModule: "manager", Status: "active", Delegable: true,
		}},
	}
	if _, err := GenerateSystemToolAuthorizationCatalog(root, report); err == nil ||
		!strings.Contains(err.Error(), "tool_audience_owner_mismatch") {
		t.Fatalf("GenerateSystemToolAuthorizationCatalog() error = %v", err)
	}
}

func TestCrossOwnerToolPermissionsRemainAnExplicitValidatedIntersection(t *testing.T) {
	for _, scenario := range []string{"valid", "missing_permission", "inactive", "non_delegable", "duplicate", "wrong_audience", "extra_scope"} {
		t.Run(scenario, func(t *testing.T) {
			root := t.TempDir()
			keys := []string{"transfer.task.create", "meta.catalog.read", "system.engine.read"}
			permissions := []PermissionDescriptor{
				{Key: keys[0], OwnerModule: "transfer", Status: "active", Delegable: true},
				{Key: keys[1], OwnerModule: "meta", Status: "active", Delegable: true},
				{Key: keys[2], OwnerModule: "system", Status: "active", Delegable: true},
			}
			audience := "transfer"
			scopes := []string{"transfer.task.config.check"}
			switch scenario {
			case "missing_permission":
				permissions = permissions[:2]
			case "inactive":
				permissions[1].Status = "disabled"
			case "non_delegable":
				permissions[2].Delegable = false
			case "duplicate":
				keys = append(keys, keys[1])
			case "wrong_audience":
				audience = "meta"
			case "extra_scope":
				scopes = append(scopes, "transfer.task.create")
			}
			data, err := json.Marshal(map[string]any{"tools": []any{map[string]any{
				"name": "transfer.task.config.check", "owner": "transfer",
				"auth": map[string]any{"audience": audience, "required_scopes": scopes, "required_permissions": keys},
			}}})
			if err != nil {
				t.Fatal(err)
			}
			writeCoverageFixture(t, root, "common-python/addp_common/tools/manifest.json", string(data))
			report := AuthorizationCatalogReport{
				SchemaVersion:       AuthorizationCatalogReportSchemaVersion,
				PermissionManifests: []PermissionManifestReference{{OwnerModule: "transfer"}, {OwnerModule: "meta"}, {OwnerModule: "system"}},
				Permissions:         permissions,
			}
			generated, err := GenerateSystemToolAuthorizationCatalog(root, report)
			if scenario != "valid" {
				if err == nil {
					t.Fatal("invalid cross-owner mapping accepted")
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(string(generated), `RequiredPermissions: []string{"meta.catalog.read", "system.engine.read", "transfer.task.create"}`) ||
				!strings.Contains(string(generated), `RequiredScopes:      []string{"transfer.task.config.check"}`) ||
				!strings.Contains(string(generated), `Owner:               "transfer"`) {
				t.Fatalf("intersection or exact delegation boundary lost: %s", generated)
			}
		})
	}
}
